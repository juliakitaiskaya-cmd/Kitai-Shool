# -*- coding: utf-8 -*-
"""Данные к статье «Слова HSK 3».

Числа действующего стандарта по уровням 1–3 сверены по сводным таблицам
стандарта в нескольких независимых источниках. Накопительное число
грамматических пунктов в источниках расходится и потому не называется.
"""

CONF = "сошлось в нескольких источниках"
SPLIT = "источники расходятся"

LEVEL = 3

# уровень: слова (прибавка, всего), знаки для узнавания (прибавка, всего),
#          знаки для письма (прибавка, всего), грамматика (прибавка)
SCALE = {
    1: dict(words=(300, 300), read=(246, 246), write=(0, 0), gram=70),
    2: dict(words=(200, 500), read=(125, 371), write=(100, 100), gram=78),
    3: dict(words=(500, 1000), read=(284, 655), write=(150, 250), gram=96),
}

# что требует третий уровень — три списка и грамматика
LISTS = [
    ("Слова", SCALE[3]["words"][0], SCALE[3]["words"][1], "весь словарь уровня"),
    ("Знаки для узнавания", SCALE[3]["read"][0], SCALE[3]["read"][1],
     "их нужно читать, но не писать"),
    ("Знаки для письма от руки", SCALE[3]["write"][0], SCALE[3]["write"][1],
     "их нужно уметь написать"),
]

GRAM_NEW = SCALE[3]["gram"]
GRAM_TOTAL = None          # накопительное число расходится: 244 или 237

OLD_WORDS = 600            # прежний стандарт на третьем уровне

# ------------------------------------------------- расчёты
W_NEW = SCALE[3]["words"][0]              # 500 новых слов
R_NEW = SCALE[3]["read"][0]               # 284 новых знака
PER_100 = int(round(100.0 * R_NEW / W_NEW))   # новых знаков на сто новых слов
FIRST_RATIO = round(SCALE[1]["read"][0] / float(SCALE[1]["words"][0]), 2)   # 0.82
THIRD_RATIO = round(R_NEW / float(W_NEW), 2)                                # 0.57
WRITE_FROM = min(l for l in SCALE if SCALE[l]["write"][0] > 0)              # 2

# ------------------------------------------------- что делать со списком
FILE_STEPS = [
    ("Сверить число позиций",
     "в действующем словнике третьего уровня их " + str(SCALE[3]["words"][1])
     + " вместе с младшими уровнями"),
    ("Отделить новые слова от прежних",
     "новых на этом уровне " + str(W_NEW) + ", остальное вы уже проходили"),
    ("Разметить знаки",
     "в файле со словами знаков нет, а их на уровне два разных списка"),
]

# ------------------------------------------------- проверки
assert set(SCALE) == {1, 2, 3}
assert SCALE[3]["words"] == (500, 1000), "прибавка и накопительная цифра уровня"
assert SCALE[1]["words"][0] + SCALE[2]["words"][0] == SCALE[3]["words"][0] == 500, \
    "третий уровень добавляет столько же, сколько первые два вместе"
assert sum(SCALE[l]["read"][0] for l in (1, 2, 3)) == SCALE[3]["read"][1] == 655, \
    "накопительные знаки для узнавания сходятся с суммой прибавок"
assert sum(SCALE[l]["write"][0] for l in (1, 2, 3)) == SCALE[3]["write"][1] == 250, \
    "накопительные знаки для письма сходятся с суммой прибавок"
assert SCALE[1]["write"][0] == 0 and WRITE_FROM == 2, \
    "письмо от руки начинается со второго уровня"
assert GRAM_TOTAL is None, "накопительную грамматику не называем — источники расходятся"
assert GRAM_NEW == 96, "прибавка грамматики подтверждена"

assert len(LISTS) == 3 and all(n and w for n, a, t, w in LISTS)
assert [a for n, a, t, w in LISTS] == [500, 284, 150], "три прибавки уровня"
assert R_NEW < W_NEW, "новых знаков меньше, чем новых слов"
assert PER_100 == 57, "на сто новых слов приходится около 57 новых знаков"
assert FIRST_RATIO > THIRD_RATIO, \
    "на первом уровне знаков на слово больше, чем на третьем"
assert 0.8 <= FIRST_RATIO <= 0.85 and 0.55 <= THIRD_RATIO <= 0.6

assert len(FILE_STEPS) == 3 and all(a and b for a, b in FILE_STEPS)
assert OLD_WORDS == 600 and OLD_WORDS < SCALE[3]["words"][1], \
    "прежний стандарт требовал меньше"

import re as _re
_TXT = " ".join([n + " " + w for n, a, t, w in LISTS] + [a + " " + b for a, b in FILE_STEPS])
assert not _re.search(r"\bруб|\bцена|\bюан", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|торрент", _TXT), "адресов и площадок в данных нет"
assert "добор" not in _TXT and "добира" not in _TXT, "жаргона в данных нет"
