# -*- coding: utf-8 -*-
"""Данные к статье «Как подготовить ребёнка к YCT 1».

PARTS — части экзамена: название, число заданий, примерные минуты, что делает ребёнок.
PLAN — дорожка подготовки: блок, недели, задача, признак готовности.
"""

TOTAL_TASKS = 35
TOTAL_MINUTES = 35
FORM_MINUTES = 10
MAX_SCORE = 200
PASS_SCORE = 120
SECTION_MAX = 100
WORDS = 80

PARTS = [
    ("аудирование", 20, 10, "слушает фразу и выбирает подходящую картинку"),
    ("чтение", 15, 15, "смотрит на картинку с подписью и решает, подходит ли она"),
    ("бланк и личные данные", 0, FORM_MINUTES,
     "вписывает свои данные до начала и переносит ответы после — это тоже экзаменационное время"),
]

PLAN = [
    ("Первый месяц", "1–4 недели", "закрыть восемьдесят слов",
     "ребёнок узнаёт слово за секунду, а не вспоминает",
     ("слушать короткие знакомые диалоги",
      "называть предметы вокруг по-китайски",
      "проверять узнавание на слух, а не по карточкам")),
    ("Второй месяц", "5–8 недели", "привыкнуть к формату заданий",
     "понимает, что от него хотят, без объяснений взрослого",
     ("разобрать каждый тип задания по одному",
      "решать без секундомера и без подсказок",
      "учиться отвечать даже при незнакомом слове")),
    ("Третий месяц", "9–12 недели", "пройти экзамен целиком по времени",
     "садится и делает все задания подряд, не отвлекаясь",
     ("прогоны целиком с бланком",
      "отмечать ответ сразу и не возвращаться",
      "разбирать после прогона, а не во время")),
]

BOOKS = [
    ("YCT 标准教程", "официальный учебный курс", "выходит томами; к учебнику есть рабочая "
                                                 "тетрадь, пропись и пособие для учителя"),
    ("сборники заданий прошлых лет", "тренировка формата", "издаются отдельно от учебника"),
]

# ----------------------------------------------------------------- проверки
assert len(PARTS) == 3, "частей три: две с заданиями и работа с бланком"
TASKS = sum(n for _, n, _, _ in PARTS)
assert TASKS == TOTAL_TASKS, "сумма заданий должна давать %d, вышло %d" % (TOTAL_TASKS, TASKS)
MINUTES = sum(m for _, _, m, _ in PARTS)
assert MINUTES == TOTAL_MINUTES, "сумма минут должна давать %d, вышло %d" % (TOTAL_MINUTES,
                                                                            MINUTES)
WITH_TASKS = [p for p in PARTS if p[1] > 0]
assert len(WITH_TASKS) == 2, "заданий два вида: аудирование и чтение"
assert WITH_TASKS[0][1] > WITH_TASKS[1][1], "аудирования больше, чем чтения"
assert all(d for _, _, _, d in PARTS), "у каждой части сказано, что делает ребёнок"

assert PASS_SCORE < MAX_SCORE, "порог ниже максимума"
assert SECTION_MAX * 2 == MAX_SCORE, "две части по сто дают двести"
assert PASS_SCORE == 120, "порог проверен по описаниям уровня"

assert len(PLAN) == 3, "подготовка разбита на три месяца"
assert len(set(p[0] for p in PLAN)) == 3, "блоки не повторяются"
ALL_DOING = [d for p in PLAN for d in p[4]]
assert len(ALL_DOING) == len(set(ALL_DOING)) == 9, "девять разных дел на три месяца"
for block, weeks, task, ready, doing in PLAN:
    assert len(doing) == 3, "в каждом блоке три дела: %s" % block
    assert all(doing), "дела заданы текстом: %s" % block
    assert "–" in weeks, "у блока указан диапазон недель: %s" % block
    assert task and ready, "у блока есть задача и признак готовности: %s" % block

WEEKS = []
for _, weeks, _, _, _ in PLAN:
    a, b = weeks.replace(" недели", "").split("–")
    WEEKS += list(range(int(a), int(b) + 1))
assert WEEKS == list(range(1, 13)), "недели идут подряд с первой по двенадцатую"

assert len(BOOKS) >= 2, "о материалах говорим не одной строкой"
assert any("标准教程" in b[0] for b in BOOKS), "официальный курс назван"
