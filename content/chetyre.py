# -*- coding: utf-8 -*-
"""Данные к статье «В каких странах цифра 4 означает смерть».

LANGS — страна, слово «четыре» и его чтение, слово «смерть» и его чтение,
сила поверья, где видно, оговорка (пустая, если расхождений нет).
"""

STRENGTH = ("сильное", "заметное", "умеренное", "спорное")

LANGS = [
    ("Китай", "四", "sì", "死", "sǐ", "сильное",
     "этажи, номера, цены", ""),
    ("Япония", "四", "shi", "死", "shi", "сильное",
     "жилые дома, больницы, парковки", ""),
    ("Корея", "사", "sa", "死", "sa", "заметное",
     "лифты, больницы, похоронные залы", ""),
    ("Вьетнам", "tư", "ты", "tử", "ты", "спорное",
     "встречается пропуск этажа", "источники расходятся: в обиходе родное слово «bốn»"),
]

JAPAN_49 = ("49", "созвучно словам «страдать и умереть»")
KOREA_F = ("F", "латинская буква вместо цифры 4 на кнопке лифта")
WEST_13 = (13, "ближайший западный аналог: тот же перенос с числа на событие")

# ----------------------------------------------------------------- проверки
assert len(LANGS) == 4, "стран в разборе четыре"
assert len(set(l[0] for l in LANGS)) == 4, "страны не должны повторяться"

for country, four, four_rd, death, death_rd, power, where, note in LANGS:
    assert four and four_rd, "у %s задано слово «четыре» и его чтение" % country
    assert death and death_rd, "у %s задано слово «смерть» и его чтение" % country
    assert power in STRENGTH, "сила поверья берётся из закрытого набора: %s" % power
    assert where, "у %s сказано, где поверье видно" % country

DISPUTED = [l for l in LANGS if l[5] == "спорное"]
assert len(DISPUTED) == 1, "спорный случай ровно один"
assert DISPUTED[0][7], "у спорного случая стоит пометка о расхождении источников"
assert all(not l[7] for l in LANGS if l[5] != "спорное"), \
    "пометка о расхождении стоит только там, где источники расходятся"

CLOSE = [l[0] for l in LANGS if l[2] == l[4]]
assert "Япония" in CLOSE and "Корея" in CLOSE, \
    "в японском и корейском чтения слов совпадают полностью"
assert "Китай" not in CLOSE, "в китайском чтения различаются тоном — об этом у соседа"

assert WEST_13[0] == 13 and JAPAN_49[0] == "49"
assert KOREA_F[0] == "F", "в корейских лифтах ставят латинскую букву"
