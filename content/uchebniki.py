# -*- coding: utf-8 -*-
"""Данные к статье «Учебники HSK 3.0».

SERIES — две серии: название, под какой стандарт, что в комплекте, статус.
KITS — что входит в комплект на каждом уровне.
"""

NEW = "New HSK Course"
OLD = "HSK Standard Course"

SERIES = [
    (NEW, "新HSK教程", "под стандарт 3.0", "официальная серия нового образца",
     "учебник и рабочая тетрадь на уровнях с первого по шестой, отдельные тома по навыкам "
     "на старших"),
    (OLD, "HSK标准教程", "под прежний стандарт", "серия предыдущего поколения",
     "учебник, рабочая тетрадь и пособие для учителя"),
]

# что лежит в комплекте на каждом уровне новой серии
LEVELS = [
    (1, ("учебник", "рабочая тетрадь")),
    (2, ("учебник", "рабочая тетрадь")),
    (3, ("учебник", "рабочая тетрадь")),
    (4, ("учебник", "рабочая тетрадь")),
    (5, ("учебник", "рабочая тетрадь")),
    (6, ("учебник", "рабочая тетрадь")),
    (7, ("аудирование", "говорение", "чтение", "письмо")),
    (8, ("аудирование", "говорение", "чтение", "письмо")),
    (9, ("аудирование", "говорение", "чтение", "письмо")),
]

WORKBOOK_PARTS = ("разбор к уроку учебника", "упражнения в формате экзамена",
                  "проверочные работы")

KNOWN_VOLUMES = [
    (1, 15, 300),
    (3, 18, 500),
]

MYTH = ("«Стандартный курс 3.0»",
        "серии с таким названием не существует: «Стандартный курс» сделан под прежний стандарт, "
        "а под 3.0 выпущена другая серия")

UNSURE = [
    ("точное число томов во всей серии", "в описаниях называют около двух десятков"),
    ("даты выхода отдельных томов", "выходят постепенно, и описания расходятся"),
    ("наличие тетрадей к старшим уровням", "часть пособий выходит позже учебников"),
]

# ----------------------------------------------------------------- проверки
assert len(SERIES) == 2, "сравниваем две серии"
assert SERIES[0][0] == NEW and SERIES[1][0] == OLD
assert "3.0" in SERIES[0][2] and "3.0" not in SERIES[1][2], \
    "под 3.0 сделана только новая серия"
assert len(set(s[0] for s in SERIES)) == 2, "названия не повторяются"

assert len(LEVELS) == 9, "уровней в стандарте девять"
assert [n for n, kit in LEVELS] == list(range(1, 10)), "уровни идут подряд"
PAIRED = [n for n, kit in LEVELS if "учебник" in kit]
BY_SKILL = [n for n, kit in LEVELS if "учебник" not in kit]
assert PAIRED == list(range(1, 7)), "пара «учебник и тетрадь» — на уровнях с первого по шестой"
assert BY_SKILL == [7, 8, 9], "старшие уровни собраны по навыкам"
assert all(len(kit) == 2 for n, kit in LEVELS if n in PAIRED)
assert all(len(kit) == 4 for n, kit in LEVELS if n in BY_SKILL), "навыков четыре"

assert len(WORKBOOK_PARTS) == 3, "в тетради три части"
assert len(set(WORKBOOK_PARTS)) == 3

for lvl, lessons, words in KNOWN_VOLUMES:
    assert lvl in PAIRED, "известные тома — из младшей половины"
    assert lessons > 10 and words >= 300, "уроков и слов названо правдоподобно: уровень %d" % lvl
assert KNOWN_VOLUMES[0][2] < KNOWN_VOLUMES[1][2], "словарь растёт от уровня к уровню"

assert "не существует" in MYTH[1], "миф назван прямо"
assert len(UNSURE) == 3, "неуверенных мест три"
assert all(len(u) == 2 and all(u) for u in UNSURE)
