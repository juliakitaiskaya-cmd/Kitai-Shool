# -*- coding: utf-8 -*-
"""Данные к статье «Что нужно знать для HSK 1–4: грамматика по уровням».

По словам и знакам числа действующего стандарта сходятся между источниками.
По грамматике — нет: в обращении два ряда чисел, и сводки сторонних
составителей расходятся в разы. Поэтому здесь приводятся оба ряда и разброс,
а единственное «правильное» число не называется.
"""

CONF = "сошлось в нескольких источниках"
TWO = "в обращении два ряда чисел"
SPLIT = "сводки расходятся в разы"

# ---------------------------------------------- грамматика: два ряда
# ряд A: накопительно 70, 148, 244, 339
GRAM_A = {1: 70, 2: 78, 3: 96, 4: 95}
# ряд B: накопительно 66, 141, 237, 331
GRAM_B = {1: 66, 2: 75, 3: 96, 4: 94}

CUM_A = {1: 70, 2: 148, 3: 244, 4: 339}
CUM_B = {1: 66, 2: 141, 3: 237, 4: 331}

# ---------------------------------------------- сторонние сводки: сколько пунктов всего
COLLECTIONS = [231, 428, 512, 572, 593]

# ---------------------------------------------- прибавки слов по уровням
WORDS = {1: 300, 2: 200, 3: 500, 4: 1000}

# ---------------------------------------------- что входит в требования уровня
REQS = [
    ("Слова", "числа сходятся", CONF),
    ("Знаки для узнавания", "числа сходятся", CONF),
    ("Знаки для письма от руки", "числа сходятся", CONF),
    ("Грамматика", "единого счёта нет", TWO),
]

# ---------------------------------------------- чего нет в списках грамматики
NO_IN_LIST = [
    ("Единого перечня", "у каждого составителя свой состав и свой счёт"),
    ("Разметки по заданиям", "в каком задании спросят конструкцию, нигде не сказано"),
    ("Порога «знаю»", "список не говорит, узнавать конструкцию или строить её самому"),
]

# ---------------------------------------------- расчёты
DIFF = {l: GRAM_A[l] - GRAM_B[l] for l in (1, 2, 3, 4)}
MAXDIFF = max(DIFF.values())
SPREAD = max(COLLECTIONS) - min(COLLECTIONS)
SPREAD_TIMES = round(max(COLLECTIONS) / float(min(COLLECTIONS)), 1)
WORDS_JUMP = WORDS[4] // WORDS[3]              # во сколько раз выросла прибавка слов
GRAM_FLAT_A = GRAM_A[3] - GRAM_A[4]            # 1 — грамматика на четвёртом не выросла
GRAM_FLAT_B = GRAM_B[3] - GRAM_B[4]            # 2

# ---------------------------------------------- проверки
assert sorted(GRAM_A) == sorted(GRAM_B) == [1, 2, 3, 4]
assert sum(GRAM_A[l] for l in (1, 2, 3, 4)) == CUM_A[4], "ряд A сходится с накопительным"
assert sum(GRAM_B[l] for l in (1, 2, 3, 4)) == CUM_B[4], "ряд B сходится с накопительным"
assert CUM_A[4] == 339 and CUM_B[4] == 331, "накопительные числа по рядам"
assert MAXDIFF <= 4, "ряды расходятся на единицы, а не в разы"
assert GRAM_A[3] == GRAM_B[3] == 96, "на третьем уровне ряды совпали"

assert GRAM_FLAT_A > 0 and GRAM_FLAT_B > 0, \
    "на четвёртом уровне грамматики добавляется не больше, чем на третьем"
assert WORDS_JUMP == 2, "прибавка слов на четвёртом уровне вдвое больше, чем на третьем"
assert WORDS[4] > WORDS[3] and GRAM_A[4] < GRAM_A[3], \
    "словарь растёт, грамматика — нет: это и есть находка"

assert len(COLLECTIONS) == 5 and COLLECTIONS == sorted(COLLECTIONS)
assert SPREAD == 362 and SPREAD_TIMES >= 2.5, "разброс сводок больше чем в два с половиной раза"

assert len(REQS) == 4 and sum(1 for n, w, s in REQS if s == CONF) == 3, \
    "три требования с сошедшимися числами, одно — нет"
assert REQS[3][0] == "Грамматика" and REQS[3][2] == TWO

assert len(NO_IN_LIST) == 3 and all(a and b for a, b in NO_IN_LIST)

import re as _re
_TXT = " ".join([n + " " + w for n, w, s in REQS] + [a + " " + b for a, b in NO_IN_LIST])
assert not _re.search(r"\bруб|\bцена|\bюан", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|торрент", _TXT), "адресов и площадок в данных нет"
assert not _re.search(r"добор|добира|добрат", _TXT), "жаргона в данных нет"
