# -*- coding: utf-8 -*-
"""Данные к статье «HSK Standard Course в электронном виде».

PARTS — часть комплекта и есть ли она официально в электронном виде.
DIFFS — чем найденная в сети копия отличается от купленного комплекта:
последствие названо практическое, а не моральное.
"""

# название части, официально в электронном виде, как получают
PARTS = [
    ("звук к учебнику", True, "по коду на задней обложке"),
    ("звук к рабочей тетради", True, "тем же кодом, в изданиях последних лет"),
    ("учебник целиком", False, None),
    ("рабочая тетрадь целиком", False, None),
    ("книга для преподавателя", False, None),
]

# признак, что с ним у копии, чем это оборачивается на занятиях
DIFFS = [
    ("звук", "кода на сканированной обложке нет или он уже погашен",
     "аудирование приходится искать отдельно и подбирать на слух к урокам"),
    ("издание", "по скану не видно, какого года издание",
     "часть заданий может быть из прежней редакции"),
    ("метка тома", "буква A или B на скане теряется или обрезается",
     "на старших уровнях легко взять вторую половину вместо первой"),
    ("тетрадь", "в сеть попадает учебник, тетрадь — заметно реже",
     "самостоятельная работа остаётся без упражнений"),
    ("распознавание", "иероглифы в тексте местами слиты или подменены",
     "ошибку принимают за незнакомое написание и заучивают её"),
]

AUDIO_WAY = "код на задней обложке"
PUBLISHER_SITE_CHECKED = False  # сайт издательства из рабочей среды не открывается

# ----------------------------------------------------------------- расчёты
DIGITAL = [p for p in PARTS if p[1]]
PAPER = [p for p in PARTS if not p[1]]
BOOKS_IN_KIT = len(PAPER)

# ----------------------------------------------------------------- проверки
assert len(PARTS) == 5, "частей комплекта пять"
assert len(DIGITAL) == 2 and len(PAPER) == 3, "в электронном виде официально только звук"
assert all("звук" in name for name, d, how in DIGITAL), \
    "всё, что открывается кодом, — это звук"
assert not any("звук" in name for name, d, how in PAPER), "книги кодом не открываются"
assert all(how for name, d, how in DIGITAL), "для каждой доступной части сказано, как её взять"
assert all(how is None for name, d, how in PAPER), "для недоступных способа не придумываем"
assert BOOKS_IN_KIT == 3, "книг в комплекте тома три, и ни одной нет официально в сети"

assert len(DIFFS) == 5, "различий пять"
assert len(set(k for k, a, b in DIFFS)) == 5, "признаки не повторяются"
assert all(a and b for k, a, b in DIFFS), "у каждого признака названы и причина, и последствие"
assert not PUBLISHER_SITE_CHECKED, "состав сайта издательства не проверен — так и пишем"
