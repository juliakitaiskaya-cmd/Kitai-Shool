# -*- coding: utf-8 -*-
"""Данные к статье «HSK и intermediate: почему таблицы нет».

Статья узкая и отвечает на один ключ из брифа — тот, на который у нас
нет своего разбора: человек видит в анкете или вакансии слова
intermediate и upper intermediate и не знает, какой сертификат этому
соответствует.

Чего здесь намеренно нет: разбора самих схем соответствия с европейской
шкалой. Спор двух схем разобран в нашей статье про уровни знания
китайского, и пересказывать его нельзя. Здесь другое — что делать
практически, когда единой таблицы не существует.

Числа взяты из наших же разборов баллов.
"""

# уровень → (максимум баллов, порог сдачи)
SCORES = {1: (200, 120), 2: (200, 120), 3: (300, 180),
          4: (300, 180), 5: (300, 180), 6: (300, 180)}

# словесные ступени, которые встречаются в анкетах и требованиях
WORDS = ["beginner", "elementary", "intermediate", "upper intermediate",
         "advanced"]

# что теряется на каждом шаге перевода
# (шаг, что было, что стало, сколько значений осталось)
STEPS = [
    ("Экзамен", "балл за каждый раздел", "три числа по сто баллов", 300),
    ("Сертификат", "сумма баллов", "уровень от первого до шестого", 6),
    ("Анкета", "уровень", "слово из короткого списка", 5),
]

# что писать вместо слова
FORMULA = [
    ("Сертификат и уровень", "название экзамена с номером уровня", "это проверяемо"),
    ("Год сдачи", "месяц и год", "у сертификата есть срок действия"),
    ("Балл, если он высокий", "число из сертификата", "внутри уровня разброс большой"),
]

# ----------------------------------------------------------------- расчёты
MAXES = sorted({v[0] for v in SCORES.values()})
PASS = sorted({v[1] for v in SCORES.values()})
TOP, THRESHOLD = 300, 180
SPREAD = TOP - THRESHOLD          # разброс баллов внутри одного сданного уровня
SHARE = int(round(100.0 * THRESHOLD / TOP))

LEVELS_N = len(SCORES)
WORDS_N = len(WORDS)
LOSS = [s[3] for s in STEPS]

# во сколько раз сужается шкала на каждом шаге
NARROW_1 = round(LOSS[0] / float(LOSS[1]), 0)
NARROW_2 = round(LOSS[1] / float(LOSS[2]), 1)

# ----------------------------------------------------------------- проверки
assert LEVELS_N == 6, "уровней шесть"
assert MAXES == [200, 300] and PASS == [120, 180], "два максимума и два порога"
assert SHARE == 60, "порог везде шестьдесят процентов"
assert SPREAD == 120, "внутри сданного уровня разброс сто двадцать баллов"
assert WORDS_N == 5 and "intermediate" in WORDS and "upper intermediate" in WORDS, \
    "словесная шкала из пяти ступеней, обе из брифа на месте"

assert len(STEPS) == 3 and LOSS == [300, 6, 5], "три шага сужения: %s" % LOSS
assert LOSS == sorted(LOSS, reverse=True), "на каждом шаге значений меньше"
assert NARROW_1 == 50.0, "от баллов к уровню шкала сужается в пятьдесят раз"
assert NARROW_2 == 1.2, "от уровня к слову — ещё немного"
assert len(FORMULA) == 3 and all(len(f) == 3 and all(f) for f in FORMULA)

import re as _re
_TXT = " ".join([x for s in STEPS for x in s if isinstance(x, str)]
                + [x for f in FORMULA for x in f])
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
assert not _re.search(r"A1|B2|C2|CEFR", _TXT), \
    "схемы соответствия разобраны у соседа и сюда не переносятся"
