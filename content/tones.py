# -*- coding: utf-8 -*-
"""Данные по тонам путунхуа. Один список на статью и на обе картинки.

Поля: номер, название, как движется голос, запись высот по пятиступенной шкале,
слог с диакритикой, иероглиф, значение, точки траектории по шкале 1–5.
"""

TONES = [
    (1, "первый", "ровно и высоко", "55", "mā", "妈", "мама", (5, 5)),
    (2, "второй", "снизу вверх", "35", "má", "麻", "онемение, покалывание", (3, 5)),
    (3, "третий", "вниз и немного вверх", "214", "mǎ", "马", "лошадь", (2, 1, 4)),
    (4, "четвёртый", "сверху вниз", "51", "mà", "骂", "ругать", (5, 1)),
]

NEUTRAL = (0, "нейтральный", "коротко и без своей высоты", "—", "ma", "吗",
           "вопросительная частица", (3,))

# ----------------------------------------------------------------- проверки
assert len(TONES) == 4, "основных тонов должно быть четыре"
assert [t[0] for t in TONES] == [1, 2, 3, 4], "номера тонов идут подряд"

tr = [t[7] for t in TONES]
assert len(set(tr)) == 4, "траектории тонов должны попарно различаться"

assert tr[0][0] == tr[0][-1], "у первого тона начало и конец на одной высоте"
assert tr[1][0] < tr[1][-1], "второй тон идёт вверх"
assert min(tr[2]) < tr[2][0] and tr[2][-1] > min(tr[2]), "у третьего тона есть спуск и подъём"
assert tr[3][0] > tr[3][-1], "четвёртый тон идёт вниз"

for num, name, move, digits, syl, han, mean, pts in TONES:
    assert digits == "".join(str(p) for p in pts), \
        "запись высот у %s тона не совпадает с траекторией: %s против %s" % (name, digits, pts)

assert all("конопля" not in str(t) for t in TONES + [NEUTRAL]), \
    "слово «конопля» в данные не берём — прямая просьба заказчика"

assert len(set(t[5] for t in TONES)) == 4, "иероглифы-примеры не должны повторяться"
assert len(set(t[4] for t in TONES)) == 4, "записи слога должны различаться знаком тона"
assert NEUTRAL[3] == "—", "у нейтрального тона своей записи высот нет"

HIGHEST = max(max(t[7]) for t in TONES)
LOWEST = min(min(t[7]) for t in TONES)
assert (LOWEST, HIGHEST) == (1, 5), "шкала должна быть от 1 до 5"
