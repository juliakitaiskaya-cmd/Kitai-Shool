# -*- coding: utf-8 -*-
"""Данные к статье «Уважительные обращения в Китае».

ADDR — обращения: знаки, пиньинь, перевод, где слышно, к кому, оговорка.
Оговорка пустая, если ограничений по месту нет.
"""

ADDR = [
    ("师傅", "shīfu", "мастер", "такси, мастерская, кухня",
     "к человеку с ремеслом: водителю, ремонтнику, повару, охраннику", ""),
    ("老师", "lǎoshī", "учитель", "школа, вуз, редакция",
     "к преподавателю, наставнику, уважаемому специалисту", ""),
    ("老板", "lǎobǎn", "хозяин", "лавка, ресторан, небольшая фирма",
     "к владельцу заведения и к тому, кто им распоряжается", ""),
    ("阿姨", "āyí", "тётя", "подъезд, двор, рынок",
     "к незнакомой женщине поколения родителей", "ошибка с возрастом слышна сразу"),
    ("叔叔", "shūshu", "дядя", "подъезд, двор, рынок",
     "к незнакомому мужчине поколения родителей", "ошибка с возрастом слышна сразу"),
    ("服务员", "fúwùyuán", "официант", "ресторан, кафе",
     "нейтральный способ позвать того, кто обслуживает", ""),
    ("美女", "měinǚ", "красавица", "магазин, салон, рынок",
     "обиходное обращение к молодой женщине в сфере услуг", "вне услуг звучит фамильярно"),
    ("帅哥", "shuàigē", "красавчик", "магазин, салон, рынок",
     "обиходное обращение к молодому мужчине в сфере услуг", "вне услуг звучит фамильярно"),
]

PREFIX = [
    ("小", "xiǎo", "小 + фамилия", "к ровеснику и младшему в коллективе"),
    ("老", "lǎo", "老 + фамилия", "к старшему и давно работающему"),
]

GONE = ("同志", "tóngzhì", "товарищ", "в обиходе вышло из употребления")

# ----------------------------------------------------------------- проверки
assert len(ADDR) == 8, "обращений в списке восемь"
assert len(set(a[0] for a in ADDR)) == len(ADDR), "знаки не должны повторяться"
assert all(a[3] for a in ADDR), "у каждого обращения задано место"
assert all(a[4] for a in ADDR), "у каждого обращения сказано, к кому оно"

NAMES = set(a[0] for a in ADDR) | {p[0] for p in PREFIX} | {GONE[0]}
for banned in ("先生", "女士", "小姐"):
    assert banned not in NAMES, "%s разобран у соседа — в данные не берём" % banned

SERVICE = [a for a in ADDR if "услуг" in a[5]]
assert len(SERVICE) == 2, "ограничение по сфере услуг стоит у двух обращений"
assert all(a[5] for a in ADDR if a[0] in ("美女", "帅哥", "阿姨", "叔叔")), \
    "у обращений с ограничениями должна стоять оговорка"

assert len(PREFIX) == 2 and PREFIX[0][0] != PREFIX[1][0], "приставок две и они разные"
assert GONE[0] not in (a[0] for a in ADDR), "вышедшее из обихода стоит отдельно от рабочих"

PLACES = []
for a in ADDR:
    for p in a[3].split(", "):
        if p not in PLACES:
            PLACES.append(p)
assert len(PLACES) >= 6, "мест на карте должно быть не меньше шести"
