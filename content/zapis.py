# -*- coding: utf-8 -*-
"""Данные к статье «Регистрация на HSK: почему запись закрывается за месяц».

Все разрывы посчитаны из таблицы нашей же статьи про даты сдачи:
она сверена 8 сентября 2026 года по объявлениям российских центров.
Числа — наш расчёт из этой таблицы, а не опубликованная величина.
"""

OUR = "наш расчёт из таблицы нашей же статьи про даты"
CHECKED = "8 сентября 2026 года"
WORLD = "по общим описаниям порядка записи"

# ------------------------------------------------- разрывы «закрытие записи → экзамен»
# (город, экзамен, последний день записи, дней до экзамена)
GAPS = [
    ("Москва", "17 октября", "17 сентября", 30),
    ("Москва", "13 декабря", "13 ноября", 30),
    ("Москва", "13 сентября", "13 августа", 31),
    ("Москва", "18 октября", "18 сентября", 30),
    ("Москва", "7 ноября", "7 октября", 31),
    ("Москва", "13 декабря", "13 ноября", 30),
    ("Петербург", "13 сентября", "14 июля", 61),
    ("Петербург", "13 декабря", "13 октября", 61),
    ("Петербург", "22 ноября", "30 сентября", 53),
    ("Петербург", "17 октября", "7 сентября", 40),
    ("Петербург", "13 декабря", "6 ноября", 37),
    ("Новосибирск", "18 октября", "26 сентября", 22),
    ("Новосибирск", "7 декабря", "7 ноября", 30),
    ("Красноярск", "18 октября", "17 сентября", 31),
    ("Красноярск", "13 декабря", "13 ноября", 30),
    ("Улан-Удэ", "8 декабря", "8 ноября", 30),
    ("Владивосток", "12–13 декабря", "4 ноября", 38),
    ("Благовещенск", "17 октября", "30 августа", 48),
    ("Благовещенск", "13 декабря", "25 октября", 49),
    ("Сочи", "13 декабря", "13 ноября", 30),
]

# ------------------------------------------------- дата, которой не было
ASKED = "8 ноября"          # её ищут в запросах
REAL = "7 ноября"           # а экзамен шёл в этот день
REAL_WEEKDAY = "суббота"
ASKED_WEEKDAY = "воскресенье"

# ближайшая сессия после осенних и состояние записи на неё
NEXT_SESSION = "13 декабря"
NEXT_CLOSED = "13 ноября"

# ------------------------------------------------- что говорят общие описания
WORLD_MIN, WORLD_MAX = 7, 14      # дней до экзамена по общим описаниям

# ------------------------------------------------- расчёты
DAYS = [d for c, e, r, d in GAPS]
MIN_D, MAX_D = min(DAYS), max(DAYS)
MONTH_N = sum(1 for d in DAYS if d in (30, 31))
TOTAL_N = len(DAYS)
MEDIAN = sorted(DAYS)[TOTAL_N // 2]
TIMES = round(MAX_D / float(MIN_D), 1)
VS_WORLD = round(MEDIAN / float(WORLD_MAX), 1)

# ------------------------------------------------- проверки
assert TOTAL_N == 20, "двадцать строк расписания"
assert MIN_D == 22 and MAX_D == 61, "крайние разрывы посчитаны, а не названы на глаз"
assert MEDIAN == 31, "середина — ровно месяц"
assert MONTH_N == 11, "у одиннадцати строк из двадцати разрыв месяц"
assert MONTH_N * 2 > TOTAL_N, "месяц — самый частый случай"
assert TIMES >= 2.5, "крайние случаи различаются больше чем вдвое"
assert VS_WORLD >= 2, "российская практика шире общих описаний вдвое и больше"
assert WORLD_MIN == 7 and WORLD_MAX == 14, "общие описания дают от недели до двух"

assert REAL_WEEKDAY == "суббота" and ASKED_WEEKDAY == "воскресенье", \
    "дни недели проверены по календарю"
assert ASKED != REAL, "ищут не ту дату, которая была"
assert NEXT_CLOSED != NEXT_SESSION, "запись на ближайшую сессию закрылась раньше"

assert all(d > 0 for d in DAYS), "разрывы положительные"
assert len(set(c for c, e, r, d in GAPS)) == 8, "восемь городов в расчёте"

import re as _re
_TXT = " ".join([c + " " + e + " " + r for c, e, r, d in GAPS])
assert not _re.search(r"\bруб|\bцена|\bстоимость", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn", _TXT), "адресов в данных нет"
assert not _re.search(r"институт|университет|гимназ|центр", _TXT, _re.I), \
    "названий центров в данных нет: только города"
