# -*- coding: utf-8 -*-
"""Данные к статье «Учебник HSK 2».

None означает, что цифру подтвердить не удалось: она так и остаётся
непроставленной и в тексте, и на картинке.
"""

CONF = "подтверждено"
OURS = "наш расчёт"
DESC = "по описаниям"

VOL_TAG = "2"
LESSONS = None          # уроков в томе — подтвердить не удалось
VOL_WORDS = None        # слов в томе — тоже

# словарь второго уровня, накопительно
LEVEL_NEW = 500         # действующий словник к концу второго уровня
LEVEL_OLD = 300         # прежний словник к концу второго уровня
PREV_NEW = 300          # действующий словник первого уровня
PREV_OLD = 150          # прежний словник первого уровня

# экзамен второго уровня по действующей редакции
EXAM = {"разделов": 2, "вопросов": 60, "минут": 55, "максимум": 200, "порог": 120}
PINYIN_LAST = 2         # последний уровень, где над иероглифами стоит пиньинь
WRITING_FROM = 3        # уровень, с которого в экзамене появляется письменная часть

# что добирать к учебнику: что, почему, как проверить
EXTRA = [
    ("Слова сверх книги", "том собран под прежний объём уровня",
     "сверить оглавление со списком действующего уровня"),
    ("Письмо от руки", "требование появилось на первом и втором уровнях",
     "написать десять знакомых слов на чистом листе"),
    ("Чтение без пиньиня", "на третьем уровне строки с пиньинем не будет",
     "закрыть пиньинь в тексте урока и прочитать вслух"),
]

# что известно про обозначение варианта пробника
CODE_PREFIX = "H2"
CODE_MEANS = "номер конкретной формы теста второго уровня"

# ----------------------------------------------------------------- расчёты
STEP_NEW = LEVEL_NEW - PREV_NEW          # прибавка на самом втором уровне
STEP_OLD = LEVEL_OLD - PREV_OLD          # прибавка по прежней шкале
RATIO = round(float(LEVEL_NEW) / LEVEL_OLD, 2)
COVER = round(100.0 * LEVEL_OLD / LEVEL_NEW)     # сколько процентов закрывает прежний объём
REST = LEVEL_NEW - LEVEL_OLD                      # сколько добирать

# ----------------------------------------------------------------- проверки
assert LESSONS is None and VOL_WORDS is None, \
    "по тому второго уровня чисел нет, и подставлять их нельзя"
assert LEVEL_NEW > LEVEL_OLD and PREV_NEW > PREV_OLD, "обе шкалы выросли"
assert STEP_NEW == 200 and STEP_OLD == 150, "прибавка на уровне считается, а не вписана"
assert STEP_NEW > STEP_OLD, "на втором уровне прибавка стала больше прежней"
assert RATIO == 1.67, "действующий словник второго уровня в 1,67 раза больше прежнего"
assert RATIO < 2.0, "на втором уровне разрыв меньше, чем на первом, где он был двукратным"
assert COVER == 60 and REST == 200, "прежний объём закрывает три пятых действующего"
assert COVER + round(100.0 * REST / LEVEL_NEW) == 100, "доли складываются в целое"

assert EXAM["разделов"] == 2 and EXAM["вопросов"] == 60, "структура второго уровня"
assert EXAM["порог"] * 100 // EXAM["максимум"] == 60, "порог — три пятых"
assert PINYIN_LAST == 2 and WRITING_FROM == 3, \
    "второй уровень — последний с пиньинем и последний без письменной части"
assert PINYIN_LAST < WRITING_FROM, "пиньинь уходит там же, где появляется письменный раздел"

assert len(EXTRA) == 3 and all(len(r) == 3 and all(r) for r in EXTRA), \
    "у каждого добора названы причина и способ проверки"
assert all("сверить" in c or "написать" in c or "закрыть" in c for a, b, c in EXTRA), \
    "каждая проверка — это действие, а не пожелание"

import re as _re
_TXT = [x for row in EXTRA for x in row] + [CODE_MEANS]
_LAT = sorted({w for s in _TXT for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT, "в данных латиница: %s" % _LAT
