# -*- coding: utf-8 -*-
"""Данные к статье «Тест HSK: какой экзамен вы сдаёте».

У каждого факта стоит статус: подтверждён официальным объявлением
экзамена или собран по сторонним описаниям. В тексте статуса не
скрываем: то, что помечено как описание, подаётся с оговоркой.
"""

OFFICIAL = "официальное объявление экзамена"
REPORTED = "сторонние описания, официально не подтверждено"

START_DATE = "13 декабря 2026 года"
LAST_OLD = "7 ноября 2026 года"
SYLLABUS_OUT = "ноябре 2025 года"

# что меняется: признак, прежняя версия, новая версия, статус
CHANGES = [
    ("Уровней", "шесть", "девять: три начальных, три средних, три высших", OFFICIAL),
    ("Устная часть", "сдаётся отдельным экзаменом",
     "входит в экзамен начиная с третьего уровня", OFFICIAL),
    ("Письмо от руки", "требований к написанию знаков нет на младших уровнях",
     "требования появляются с первого и второго уровня", OFFICIAL),
    ("Словарь первого уровня", "150 слов", "300 слов", OFFICIAL),
    ("Письменная часть шестого уровня", "одно задание: изложение прочитанного текста",
     "два задания: практический текст и сочинение", REPORTED),
]

# уровни новой версии по ступеням
BANDS = [
    ("начальная", (1, 2, 3)),
    ("средняя", (4, 5, 6)),
    ("высшая", (7, 8, 9)),
]

# что делать тому, кто готовился по прежним пробникам
STEPS = [
    ("пересчитать словарь", "цифры младших уровней выросли, разница заметнее всего на первом"),
    ("добавить письмо от руки", "на младших уровнях знаки теперь нужно писать, а не узнавать"),
    ("учесть устную часть", "с третьего уровня она входит в экзамен, а не идёт отдельно"),
    ("перепроверить формат заданий", "описания расходятся, и это повод смотреть образцы"),
]

# ----------------------------------------------------------------- расчёты
LEVELS_OLD = 6
LEVELS_NEW = sum(len(ls) for name, ls in BANDS)
CONFIRMED = [c for c in CHANGES if c[3] == OFFICIAL]
UNCONFIRMED = [c for c in CHANGES if c[3] == REPORTED]
SPEAKING_FROM = 3

# ----------------------------------------------------------------- проверки
assert LEVELS_NEW == 9 and LEVELS_OLD == 6, "было шесть уровней, стало девять"
assert [l for name, ls in BANDS for l in ls] == list(range(1, 10)), "уровни идут подряд"
assert all(len(ls) == 3 for name, ls in BANDS), "в каждой ступени по три уровня"
assert len(BANDS) == 3, "ступеней три"

assert len(CHANGES) == 5, "различий пять"
assert len(set(c[0] for c in CHANGES)) == 5, "признаки не повторяются"
assert all(c[1] and c[2] for c in CHANGES), "у каждого различия названы обе версии"
assert all(c[3] in (OFFICIAL, REPORTED) for c in CHANGES), "у каждого различия есть статус"
assert len(CONFIRMED) == 4 and len(UNCONFIRMED) == 1, \
    "подтверждены четыре различия из пяти, пятое помечено как описание"
assert UNCONFIRMED[0][0].startswith("Письменная часть"), \
    "неподтверждённое — именно письменная часть шестого уровня"

assert SPEAKING_FROM in (1, 2, 3, 4, 5, 6), "устная часть входит с одного из уровней"
assert len(STEPS) == 4 and all(a and b for a, b in STEPS), \
    "у каждого шага названо, что именно делать"
assert "декабря 2026" in START_DATE and "ноября 2026" in LAST_OLD, \
    "обе даты стоят в тексте и относятся к одному году"
