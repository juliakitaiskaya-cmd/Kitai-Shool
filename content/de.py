# -*- coding: utf-8 -*-
"""Данные к статье «Частица 的 (de) в китайском языке».

PARTS — знак, чтение, позиция, что вводит, пример, пиньинь примера, перевод,
короткая подсказка-вопрос, слоты схемы (левый, частица, правый).
"""

POSITIONS = ("перед существительным", "после глагола", "перед глаголом")

PARTS = [
    ("的", "de", "перед существительным", "определение к предмету",
     "我买的书", "wǒ mǎi de shū", "книга, которую я купил",
     "описывается предмет",
     ("описание", "的", "существительное")),
    ("得", "de", "после глагола", "оценку самого действия",
     "他跑得很快", "tā pǎo de hěn kuài", "он бегает очень быстро",
     "оценивается действие",
     ("глагол", "得", "оценка")),
    ("地", "de", "перед глаголом", "способ действия",
     "他慢慢地走", "tā mànmàn de zǒu", "он идёт медленно",
     "описывается, как действие произойдёт",
     ("описание", "地", "глагол")),
]

OTHER_READINGS = [
    ("得", "děi", "нужно, приходится", "我得走了"),
    ("得", "dé", "получать", "得到"),
]

DROP = [
    ("родня", "我妈妈", "wǒ māma", "моя мама"),
    ("своё близкое", "我家", "wǒ jiā", "мой дом"),
    ("односложное качество", "新书", "xīn shū", "новая книга"),
]

SHI_DE = ("我是昨天来的", "wǒ shì zuótiān lái de", "я приехал именно вчера")

# ----------------------------------------------------------------- проверки
assert len(PARTS) == 3, "частиц ровно три"
assert len(set(p[0] for p in PARTS)) == 3, "знаки не повторяются"
assert len(set(p[2] for p in PARTS)) == 3, "позиции не повторяются"

for sign, rd, pos, intro, ex, py, tr, hint, slots in PARTS:
    assert pos in POSITIONS, "позиция берётся из закрытого набора: %s" % pos
    assert rd == "de", "в нейтральной позиции все три читаются одинаково"
    assert ex and py and tr, "у %s есть пример, пиньинь и перевод" % sign
    assert sign in ex, "знак %s стоит в своём же примере" % sign
    assert len(slots) == 3 and slots[1] == sign, "в схеме средний слот — сама частица"
    assert hint, "у %s есть подсказка-вопрос" % sign

assert all(r[0] == "得" for r in OTHER_READINGS), "другие чтения есть только у 得"
assert len(set(r[1] for r in OTHER_READINGS)) == len(OTHER_READINGS), "чтения не повторяются"
assert all("的" not in d[1] for d in DROP), "в примерах на опускание частицы нет"
assert SHI_DE[0].startswith("我是") and SHI_DE[0].endswith("的")
