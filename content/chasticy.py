# -*- coding: utf-8 -*-
"""Данные к статье «Частицы в китайском языке».

GROUPS — четыре рабочие группы: название, что делает, представители, пример.
FAN — одна основа фразы и разные концовки: частица, фраза, пиньинь, перевод.
OWN — частицы, которые разбираются здесь же, а не у соседей.
"""

GROUPS = [
    ("вопросительные", "превращают утверждение в вопрос",
     ("吗", "呢", "吧"), "你去吗?", "nǐ qù ma", "ты идёшь?"),
    ("видо-временные", "говорят о завершённости, длительности и опыте",
     ("了", "着", "过"), "我去过中国", "wǒ qù guo Zhōngguó", "я бывал в Китае"),
    ("структурные", "связывают слова внутри фразы",
     ("的", "得", "地"), "我买的书", "wǒ mǎi de shū", "книга, которую я купил"),
    ("смягчающие", "задают тон и отношение говорящего",
     ("啊", "呀", "嘛"), "好啊", "hǎo a", "ну давай"),
]

BASE = ("我们走", "wǒmen zǒu", "мы идём")

FAN = [
    ("吗", "我们走吗?", "wǒmen zǒu ma", "мы идём?", "вопрос",
     "ждёте ответ: да или нет"),
    ("吧", "我们走吧", "wǒmen zǒu ba", "пойдём", "предложение",
     "ждёте, что человек встанет и пойдёт"),
    ("了", "我们走了", "wǒmen zǒu le", "мы уходим", "перемена",
     "ответа не ждёте, просто сообщаете"),
]

OWN = ["呢", "吧", "着", "过", "啊", "呀", "嘛"]
AT_NEIGHBOURS = ["吗", "的", "得", "地", "了"]

NE = [
    ("переспрос", "你呢?", "nǐ ne", "а ты?"),
    ("«а где?»", "我的书呢?", "wǒ de shū ne", "а где моя книга?"),
]

BA = [
    ("предложение", "我们走吧", "wǒmen zǒu ba", "пойдём"),
    ("предположение", "你是老师吧?", "nǐ shì lǎoshī ba", "вы ведь преподаватель?"),
]

ZHE = ("他站着", "tā zhàn zhe", "он стоит")
GUO = ("我去过中国", "wǒ qù guo Zhōngguó", "я бывал в Китае")

# ----------------------------------------------------------------- проверки
assert len(GROUPS) == 4, "групп ровно четыре"
assert len(set(g[0] for g in GROUPS)) == 4, "названия групп не повторяются"
for name, what, members, ex, py, tr in GROUPS:
    assert len(members) == 3, "в каждой группе по три представителя: %s" % name
    assert any(m in ex for m in members), "пример группы «%s» показывает её частицу" % name
    assert py and tr, "у примера есть пиньинь и перевод: %s" % name

ALL = [m for g in GROUPS for m in g[2]]
assert len(ALL) == len(set(ALL)), "одна частица не попадает в две группы"

assert len(FAN) == 3, "концовок в веере три"
assert len(set(f[0] for f in FAN)) == 3, "частицы в веере не повторяются"
for sign, ex, py, tr, role, expect in FAN:
    assert ex.startswith(BASE[0]), "все концовки растут из одной основы: %s" % ex
    assert sign in ex, "частица стоит в своей же фразе: %s" % sign
    assert expect, "у каждой концовки сказано, какой реакции ждут: %s" % sign
assert len(set(f[5] for f in FAN)) == 3, "ожидаемые реакции различаются"
assert len(set(f[3] for f in FAN)) == 3, "переводы концовок различаются"

assert not (set(OWN) & set(AT_NEIGHBOURS)), "частица либо наша, либо соседская, не обе сразу"
assert set(OWN) | set(AT_NEIGHBOURS) >= set(ALL), "каждая частица из групп где-то разобрана"
assert all("呢" in n[1] for n in NE), "в примерах на 呢 частица стоит"
assert all("吧" in b[1] for b in BA), "в примерах на 吧 частица стоит"
assert "着" in ZHE[0] and "过" in GUO[0]
