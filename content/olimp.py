# -*- coding: utf-8 -*-
"""Данные к статье «Олимпиада по китайскому: почему экзаменационная
подготовка к ней не готовит».

Ось узкая и выбрана заказчиком. Что занято и сюда не идёт: какие
олимпиады дают льготы и как проверить перечень — это разобрано
в опубликованной статье про китайский для детей.

Источники — только наша практика, это тоже решение заказчика. Поэтому
здесь нет: названий олимпиад и площадок, городов, дат, числа заданий
по классам и ответов к ним. Любое такое число меняется от года к году
и от региона к региону, а выдумывать мы не станем.

Числовой якорь один и взят из наших же разборов системы оценки: порог
экзамена — три пятых от максимума. Он нужен, чтобы показать разницу
между абсолютной шкалой и относительной.
"""

SHARE = 60          # порог экзамена в процентах, из наших разборов оценки

# что известно заранее — главное различие двух подготовок
KNOWN = [
    ("Список материала", "да", "нет",
     "словник ступени объявлен заранее и конечен"),
    ("Формат заданий", "да", "частично",
     "разделы экзамена постоянны, олимпиадные меняются от года к году"),
    ("Что считается успехом", "да", "нет",
     "у экзамена это доля верных ответов, у олимпиады — место среди других"),
    ("Ваш результат при идеальной работе", "да", "нет",
     "на экзамене это максимум, на олимпиаде зависит от чужих работ"),
]

# четыре следствия для подготовки
HOW = [
    ("Учить не список, а приёмы",
     "список кончится, а незнакомое слово на олимпиаде будет всегда",
     "важнее догадываться по составу знака и по соседним словам"),
    ("Тренировать незнакомый текст",
     "экзаменационные тексты подогнаны под ступень, олимпиадные — нет",
     "брать тексты заведомо выше своего уровня и работать с ними"),
    ("Считать время, а не только ответы",
     "на олимпиаде заданий часто больше, чем можно успеть",
     "учиться выбирать, что решать первым, и бросать неподъёмное"),
    ("Писать развёрнуто",
     "там, где экзамен просит выбрать, олимпиада часто просит объяснить",
     "короткий ответ без обоснования теряет баллы"),
]

# что спросить у организаторов вместо поиска ответов в интернете
ASK = [
    ("Какие классы допускаются", "правила по возрасту у всех разные"),
    ("Сколько этапов и как попасть на первый", "где-то через школу, где-то сам"),
    ("Что именно проверяют", "перечень разделов обычно публикуют заранее"),
    ("Есть ли устная часть", "она меняет подготовку сильнее всего"),
    ("Что даёт диплом именно этой олимпиады", "ответ бывает неожиданным"),
]

# ----------------------------------------------------------------- проверки
assert SHARE == 60, "порог экзамена — три пятых"

assert len(KNOWN) == 4 and all(len(k) == 4 and all(k) for k in KNOWN)
assert [k[1] for k in KNOWN] == ["да", "да", "да", "да"], \
    "у экзамена заранее известно всё четыре"
assert [k[2] for k in KNOWN].count("нет") == 3, \
    "у олимпиады заранее не известно почти ничего"

assert len(HOW) == 4 and all(len(h) == 3 and all(h) for h in HOW)
assert len(ASK) == 5 and all(len(a) == 2 and all(a) for a in ASK)

import re as _re
_TXT = " ".join(x for g in (KNOWN, HOW, ASK) for t in g for x in t)
# фактов, которых мы не проверяли, в данных нет
assert not _re.search(r"ВсОШ|Казан|Москв|2026|2027|перечн|льгот", _TXT), \
    "названий, городов, дат и темы льгот здесь нет"
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
