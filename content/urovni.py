# -*- coding: utf-8 -*-
"""Данные к статье «Уровни знания китайского».

LEVELS — девять уровней нового стандарта: номер, ступень, что умеешь, пометка.
BANDS — три ступени: название, номера уровней, чем отличается.
EXAM79 — параметры экзамена верхней ступени.
CEFR — таблицы соответствия: чья и что в ней.
"""

LEVELS = [
    (1, "начальная", "представиться и назвать простые вещи", "весь текст с пиньинем"),
    (2, "начальная", "бытовые диалоги в знакомых ситуациях", ""),
    (3, "начальная", "обсудить привычные темы, читать без пиньиня", "появляется письмо"),
    (4, "средняя", "длинные тексты и свободная бытовая речь", "рабочий минимум для вуза"),
    (5, "средняя", "пресса, абстрактные темы, синонимы", ""),
    (6, "средняя", "сложные тексты и развёрнутое мнение", "верх нынешней шкалы"),
    (7, "высшая", "профессиональные тексты и обсуждение специальных тем", ""),
    (8, "высшая", "свободная работа с источниками и перевод", ""),
    (9, "высшая", "уровень, близкий к профессиональной работе с языком", "высший уровень"),
]

BANDS = [
    ("начальная", (1, 2, 3), "базовое общение"),
    ("средняя", (4, 5, 6), "учёба и работа"),
    ("высшая", (7, 8, 9), "профессиональная работа с языком"),
]

EXAM79 = {
    "задания": 98,
    "минуты": 210,
    "навыки": ("аудирование", "говорение", "чтение", "письмо", "перевод"),
    "первый экзамен": "26 ноября 2022 года",
    "словарь": "около 11 000 слов",
}

STANDARD = {
    "имя": "国际中文教育中文水平等级标准",
    "код": "GF 0025—2021",
    "опубликован": "март 2021 года",
    "вступил в силу": "июль 2021 года",
}

CEFR = [
    ("официальная таблица", 2010, "HSK 1–6 приравнены к A1–C2"),
    ("немецкая ассоциация преподавателей китайского", 2010,
     "HSK 6 отвечает B2, HSK 5 — B1, HSK 4 — A2"),
]

OLD_MAX = 6          # сколько уровней в нынешней системе

# ----------------------------------------------------------------- проверки
assert len(LEVELS) == 9, "уровней девять"
assert [l[0] for l in LEVELS] == list(range(1, 10)), "уровни идут подряд с первого по девятый"

assert len(BANDS) == 3, "ступеней три"
assert all(len(b[1]) == 3 for b in BANDS), "в каждой ступени по три уровня"
assert sorted(n for b in BANDS for n in b[1]) == list(range(1, 10)), \
    "ступени покрывают все девять уровней без пропусков"

for num, band, what, note in LEVELS:
    assert band in [b[0] for b in BANDS], "ступень %s должна быть в списке ступеней" % band
    assert num in dict((b[0], b[1]) for b in BANDS)[band], \
        "уровень %d отнесён не к своей ступени" % num

assert [l[0] for l in LEVELS][:OLD_MAX] == list(range(1, OLD_MAX + 1)), \
    "первые шесть уровней совпадают по номерам со старой шкалой"

assert EXAM79["задания"] == 98 and EXAM79["минуты"] == 210, "параметры экзамена заданы один раз"
assert len(EXAM79["навыки"]) == 5, "в экзамене верхней ступени пять навыков"
assert "перевод" in EXAM79["навыки"], "пятый навык — перевод"
assert EXAM79["словарь"].startswith("около"), \
    "словарь даём порядком величины: точную цифру подтвердить не удалось"

assert "11 092" not in str(EXAM79), "точная цифра словаря в данные не берётся"
assert len(CEFR) == 2 and CEFR[0][2] != CEFR[1][2], \
    "две таблицы соответствия, и они расходятся"
