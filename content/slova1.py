# -*- coding: utf-8 -*-
"""Данные к статье «Слова HSK 1».

Числа действующего стандарта по первому уровню сверены по описаниям
стандарта в нескольких независимых источниках. Там, где источники
расходятся (знаки для написания от руки), число не называется.
"""

CONF = "сошлось в нескольких источниках"
ONE = "в одном источнике, не подтверждено"
SPLIT = "источники расходятся"

# ------------------------------------------------- числа первого уровня
WORDS = 300              # слов в словнике первого уровня
CHARS_READ = 246         # знаков для узнавания
CHARS_WRITE = None       # знаки для написания: источники расходятся (ноль или сто)
GRAMMAR = 70             # грамматических пунктов
OLD_WORDS = 150          # прежний стандарт

# что из этого мы утверждаем и с какой пометкой
FACTS = [
    ("Слов в словнике", WORDS, CONF),
    ("Знаков для узнавания", CHARS_READ, CONF),
    ("Грамматических пунктов", GRAMMAR, CONF),
    ("Знаков для написания от руки", None, SPLIT),
]

# ------------------------------------------------- как устроен словник
ORDER = "по алфавиту пиньиня"
NO_TOPICS = True         # официального деления по темам в словнике нет
TOPICS_CLAIM = ("30 тем и 59 речевых задач", ONE)

# ------------------------------------------------- что делать со списком
STEPS = [
    ("Посчитать позиции", "в действующем словнике первого уровня их " + str(WORDS)),
    ("Отметить знакомое", "в работу идёт только остаток, а не весь список"),
    ("Разложить остаток по своим группам",
     "деления по темам в словнике нет, и группы вы задаёте сами"),
]

# ------------------------------------------------- поля карточки
CARD = [
    ("Иероглифы", True, "без них карточка не про письменный язык"),
    ("Чтение", True, "тон записывается знаком, а не цифрой"),
    ("Перевод", True, "одно значение, а не весь словарный ряд"),
    ("Пример с этим словом", True, "на первом уровне — короткая фраза из знакомых слов"),
    ("Номер урока учебника", False, "привязывает слово к книге, а не к уровню"),
]

# ------------------------------------------------- расчёты
RATIO = round(WORDS / CHARS_READ, 2)          # слов на один знак
GAP = WORDS - CHARS_READ                      # насколько слов больше, чем знаков
GROWTH = WORDS // OLD_WORDS                   # во сколько раз выросло требование
YES_CARD = [c for c in CARD if c[1]]
NO_CARD = [c for c in CARD if not c[1]]

# ------------------------------------------------- проверки
assert WORDS == 300 and OLD_WORDS == 150, "числа уровня взяты из сверки, а не на глаз"
assert GROWTH == 2, "требование по словам выросло ровно вдвое"
assert CHARS_READ < WORDS, "знаков для узнавания меньше, чем слов"
assert GAP == 54, "разница между словами и знаками посчитана, а не названа на глаз"
assert 1.2 <= RATIO <= 1.3, "на один знак приходится примерно одно слово с небольшим"
assert CHARS_WRITE is None, "число знаков для письма от руки не подтверждено — не называем"

assert len(FACTS) == 4
assert sum(1 for n, v, s in FACTS if s == CONF) == 3, "три числа подтверждены"
assert [v for n, v, s in FACTS if s == SPLIT] == [None], "спорное число не названо"
assert all(v is None or isinstance(v, int) for n, v, s in FACTS)

assert NO_TOPICS is True, "деления по темам в словнике нет — это ядро статьи"
assert ORDER == "по алфавиту пиньиня", "порядок в словнике алфавитный"
assert TOPICS_CLAIM[1] == ONE, "про число тем стоит пометка о единственном источнике"

assert len(STEPS) == 3 and all(a and b for a, b in STEPS)
assert str(WORDS) in STEPS[0][1], "в первом шаге названо число позиций"

assert len(CARD) == 5 and len(YES_CARD) == 4 and len(NO_CARD) == 1
assert NO_CARD[0][0].startswith("Номер урока"), "поле, которого быть не должно, одно"

import re as _re
_TXT = " ".join([n for n, v, s in FACTS] + [a + " " + b for a, b in STEPS]
                + [n + " " + w for n, y, w in CARD] + [TOPICS_CLAIM[0], ORDER])
assert not _re.search(r"\bруб|\bцена|\bюан", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|торрент", _TXT), "адресов и площадок в данных нет"
assert "добор" not in _TXT and "добира" not in _TXT, "жаргона в данных нет"
