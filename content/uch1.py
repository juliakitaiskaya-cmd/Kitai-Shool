# -*- coding: utf-8 -*-
"""Данные к статье «Учебник HSK 1: какой том брать и как заниматься по уроку».

Числа по тому взяты с нашей же страницы про серию, где они стоят с
пометкой «совпали в нескольких описаниях». Словник уровня — по финальному
словнику. Вывод о покрытии считается, а не вписывается.
"""

CONF = "подтверждено"
OURS = "наш расчёт"
PRACT = "практика"

# том первого уровня
VOL_TAG = "1"
LESSONS = 15            # уроков в томе
VOL_WORDS = 150         # слов в томе, примерно
LEVEL_WORDS = 300       # действующий словник первого уровня
OLD_LEVEL_WORDS = 150   # словник прежней редакции

# четыре подхода к одному уроку: подход, что делаем, сколько минут
STEPS = [
    ("Слова", "разбираем список новых слов: звучание, тон, запись", 25),
    ("Текст на слух", "слушаем текст урока, не глядя в книгу, два-три раза", 15),
    ("Текст глазами", "читаем текст и разбираем то, что не услышали", 25),
    ("Упражнения", "делаем задания рабочей тетради к этому уроку", 25),
]

# чем русскоязычный учебник отличается от китайского
RU_VS_CN = [
    ("Пояснения грамматики", "на русском, с привычными терминами",
     "на китайском и английском"),
    ("Порядок тем", "подогнан под уровень экзамена", "подогнан под уровень экзамена"),
    ("Разбор ошибок носителей русского", "есть", "нет: серия общая для всех языков"),
    ("Привыкание к китайскому в учебнике", "откладывается", "начинается сразу"),
]

# русскоязычная серия под уровни экзамена, проверенная по карточке магазина
RU_BOOK = "Китайский язык. Новая эра: базовый курс. Уровень HSK 1"
RU_AUTHORS = "Мин Гун и Юлия Селиверстова"

# чего в учебнике нет
NOT_IN = [
    ("письма от руки как отдельной работы", "требование появилось на первом уровне недавно"),
    ("формата экзамена целиком", "это задача пробника, а не учебника"),
    ("второй половины действующего словаря", "том собран под прежний объём уровня"),
]

# ----------------------------------------------------------------- расчёты
COVER = round(100.0 * VOL_WORDS / LEVEL_WORDS)       # сколько процентов уровня закрывает том
REST = LEVEL_WORDS - VOL_WORDS                        # сколько слов добирать
MIN_PER_LESSON = sum(m for n, w, m in STEPS)          # минут на урок целиком
WEEKS_ONE = LESSONS                                   # по уроку в неделю
WEEKS_TWO = (LESSONS + 1) // 2                        # по два урока в неделю
WORDS_PER_LESSON = round(float(VOL_WORDS) / LESSONS)

# ----------------------------------------------------------------- проверки
assert LESSONS == 15 and VOL_WORDS == 150, "числа тома совпадают с нашей же страницей"
assert LEVEL_WORDS == 2 * OLD_LEVEL_WORDS, "словник уровня вырос ровно вдвое"
assert VOL_WORDS == OLD_LEVEL_WORDS, \
    "том собран под прежний объём уровня — на этом и держится вся находка"
assert COVER == 50, "том закрывает ровно половину действующего словаря"
assert REST == 150 and REST + VOL_WORDS == LEVEL_WORDS, "вторая половина считается, а не вписана"
assert WORDS_PER_LESSON == 10, "около десяти слов на урок"

assert len(STEPS) == 4, "подходов четыре"
assert [n for n, w, m in STEPS] == ["Слова", "Текст на слух", "Текст глазами", "Упражнения"], \
    "порядок подходов: слова, слух, глаза, упражнения"
assert STEPS[1][2] < STEPS[0][2], "слушание короче разбора слов"
assert MIN_PER_LESSON == 90, "урок целиком — полтора часа работы"
assert all(m > 0 for n, w, m in STEPS), "у каждого подхода своё время"
assert "не глядя в книгу" in STEPS[1][1], "слух идёт до чтения, иначе это не слух"

assert len(RU_VS_CN) == 4 and all(len(r) == 3 for r in RU_VS_CN), "сравнение по четырём строкам"
assert RU_VS_CN[1][1] == RU_VS_CN[1][2], "по порядку тем разницы нет, и это сказано прямо"
assert sum(1 for a, b, c in RU_VS_CN if b != c) == 3, "разница есть в трёх строках из четырёх"

assert len(NOT_IN) == 3 and all(a and b for a, b in NOT_IN), "у каждой нехватки названа причина"

import re as _re
_TXT = [x for row in STEPS + RU_VS_CN + NOT_IN for x in row if isinstance(x, str)]
_TXT += [RU_BOOK, RU_AUTHORS]
_LAT = sorted({w for s in _TXT for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert _LAT == ["HSK"], "в данных латиница кроме HSK: %s" % _LAT
assert not _re.search(r"\d+\s*(?:₽|руб)", " ".join(_TXT)), "цен в данных нет"
