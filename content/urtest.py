# -*- coding: utf-8 -*-
"""Данные к статье «Тест на уровень китайского языка».

Ось узкая и выбрана заказчиком: не «где пройти тест» (это разобрано
в нашей статье про пробный тест HSK) и не «как уровни соотносятся
с экзаменом» (это в статье про уровни знания китайского), а другое —
почему короткий онлайн-тест не определяет уровень и как определить
его честно.

Главный расчёт — вероятность пройти порог чистым угадыванием при
разной длине теста и разном числе вариантов ответа. Это обычная
школьная вероятность, посчитанная здесь же, а не чья-то оценка.

Числа заданий на экзамене взяты из наших же разборов уровней.
"""
from math import comb

PASS_SHARE = 0.6          # порог: три пятых верных ответов
VARIANTS = (4, 2)         # четыре варианта и «верно или нет»

# сколько заданий на настоящем экзамене — из наших разборов уровней
TASKS = {1: 40, 2: 60, 3: 80, 4: 100, 5: 100}

# длины тестов, которые сравниваем
LENGTHS = [5, 10, 20, 40, 60, 80, 100]


def need(n):
    """Сколько верных ответов нужно, чтобы взять порог при длине n."""
    return -(-int(round(PASS_SHARE * 100)) * n // 100)


def luck(n, variants):
    """Вероятность взять порог, отвечая наугад."""
    p = 1.0 / variants
    k = need(n)
    return sum(comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k, n + 1))


def one_in(n, variants):
    """Та же вероятность словами: один случай из скольких."""
    v = luck(n, variants)
    return int(round(1 / v)) if v else 0


TABLE = [(n, need(n), luck(n, 4), luck(n, 2)) for n in LENGTHS]

SHORT = 10                 # типичная длина короткого теста
SHORT_ONE_IN = one_in(SHORT, 4)      # 51
TINY_ONE_IN = one_in(5, 4)           # 10
REAL = TASKS[1]                      # 40 — самый короткий настоящий экзамен
REAL_ONE_IN = one_in(REAL, 4)        # 353 861
COIN_ONE_IN = one_in(REAL, 2)        # 7

# что тест с выбором ответа меряет, а что нет
MEASURES = [
    ("Узнавание слова", "да", "ответ уже на экране, его нужно только выбрать"),
    ("Понимание на слух", "частично",
     "зависит от записи и от того, сколько раз её дают послушать"),
    ("Письмо от руки", "нет", "выбором из вариантов знак не напишешь"),
    ("Речь", "нет", "это отдельный экзамен и отдельный результат"),
]

# три честные проверки вместо одного теста
CHECKS = [
    ("Узнавание", "взять список слов своего предполагаемого уровня",
     "отмечать не «видел», а «понимаю без подсказки»"),
    ("Слух", "включить запись для этого уровня без текста перед глазами",
     "считать не общее впечатление, а долю понятых заданий"),
    ("Письмо", "написать от руки несколько знаков из списка",
     "это то, что выбором ответа не проверяется вовсе"),
]

# ----------------------------------------------------------------- проверки
assert need(10) == 6 and need(40) == 24 and need(5) == 3, "порог считается верно"
assert SHORT_ONE_IN == 51, "из десяти вопросов угадывает каждый пятьдесят первый: %d" % SHORT_ONE_IN
assert TINY_ONE_IN == 10, "из пяти — каждый десятый: %d" % TINY_ONE_IN
assert REAL_ONE_IN > 300000, "на сорока заданиях угадать уже нельзя: %d" % REAL_ONE_IN
assert COIN_ONE_IN == 7, "с двумя вариантами и на сорока — каждый седьмой: %d" % COIN_ONE_IN

assert [t[0] for t in TABLE] == LENGTHS
assert all(a[2] > b[2] for a, b in zip(TABLE, TABLE[1:])), "длиннее тест — меньше везения"
assert all(t[3] > t[2] for t in TABLE), "с двумя вариантами угадать всегда легче"
assert TASKS[1] == 40 and TASKS[3] == 80 and TASKS[5] == 100, "числа заданий из наших разборов"
assert sorted(TASKS) == [1, 2, 3, 4, 5] and list(TASKS.values()) == sorted(TASKS.values())

assert len(MEASURES) == 4 and len(CHECKS) == 3
assert all(len(m) == 3 and all(m) for m in MEASURES)
assert all(len(c) == 3 and all(c) for c in CHECKS)

import re as _re
_TXT = " ".join([x for m in MEASURES for x in m] + [x for c in CHECKS for x in c])
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
assert not _re.search(r"резюме|intermediate", _TXT), "это темы соседних статей"
