# -*- coding: utf-8 -*-
"""Данные к статье «Уровни китайского языка и их описание».

SCEN — сценарии: ситуация, уровень, с которого она перестаёт быть проблемой,
что именно получается, что при этом ещё не выходит.
MILES — вехи для обложки: уровень и короткая подпись «отсюда можете».
"""

SCEN = [
    ("меню в кафе", 2, "заказать знакомое блюдо и напиток",
     "незнакомое название всё ещё придётся показывать пальцем"),
    ("такси и дорога", 2, "назвать адрес и попросить остановить",
     "подробный разговор с водителем не выйдет"),
    ("объявление на двери", 3, "понять, что написано, без пиньиня",
     "канцелярские обороты останутся тёмными"),
    ("переписка с коллегой", 4, "вести рабочую переписку в мессенджере",
     "длинное официальное письмо ещё трудно"),
    ("новости и статьи", 5, "читать прессу и следить за темой",
     "подтекст и ирония чаще проходят мимо"),
    ("лекция в вузе", 5, "слушать лекцию и записывать",
     "спорить с преподавателем на равных пока сложно"),
    ("переговоры и доклад", 6, "выступать и отстаивать позицию",
     "шутки и местные отсылки всё ещё теряются"),
]

MILES = [
    (1, "представиться и назвать простые вещи"),
    (2, "выжить в поездке: еда, такси, покупки"),
    (3, "читать без пиньиня и жить в быту самостоятельно"),
    (4, "работать с длинным текстом и вести переписку"),
    (5, "читать прессу и слушать лекции"),
    (6, "говорить развёрнуто и отстаивать мнение"),
]

MAX_LEVEL = 6          # шкала, по которой сейчас живут требования

# ----------------------------------------------------------------- проверки
assert len(SCEN) == 7, "сценариев семь"
assert len(set(s[0] for s in SCEN)) == len(SCEN), "ситуации не должны повторяться"
assert all(1 <= s[1] <= MAX_LEVEL for s in SCEN), "уровень каждого сценария внутри шкалы"
assert all(s[2] and s[3] for s in SCEN), "у сценария задано и что выходит, и что ещё нет"
assert [s[1] for s in SCEN] == sorted(s[1] for s in SCEN), \
    "сценарии идут по возрастанию уровня"

assert len(MILES) == MAX_LEVEL, "вех столько же, сколько уровней в шкале"
assert [m[0] for m in MILES] == list(range(1, MAX_LEVEL + 1)), "вехи идут подряд"
assert len(set(m[1] for m in MILES)) == MAX_LEVEL, "подписи вех не повторяются"

BAN = ("часов", "часа", "месяц", "лет", "недел")
for row in SCEN + MILES:
    text = " ".join(str(x) for x in row)
    assert not any(b in text for b in BAN), \
        "сроки и часы разобраны у соседей — в данные не берём: %s" % text

LEVELS_USED = sorted(set(s[1] for s in SCEN))
assert LEVELS_USED == [2, 3, 4, 5, 6], "сценарии покрывают уровни со второго по шестой"
