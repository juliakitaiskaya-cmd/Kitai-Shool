# -*- coding: utf-8 -*-
"""Данные к статье «ЕГЭ по китайскому и HSK: зачем нужен каждый».

Ось узкая и выбрана заказчиком: не формат экзамена (его состав задают
официальные документы на каждый год, проверить их мы не можем) и не
соответствие уровням (такой таблицы не существует, об этом у нас уже
есть отдельная статья). Здесь другое — какой документ кто спрашивает
и почему один не засчитывается вместо другого.

Про ОГЭ по китайскому в статье честный отказ: подтвердить, что он
проводится, мы не можем, а утверждать наугад не станем. Это тоже
решение заказчика.

Чисел школьного экзамена здесь нет: шкалу и состав задают официальные
документы. Единственный числовой якорь — устройство HSK из наших же
разборов.
"""

LEVELS = 6          # ступеней у международного экзамена
SHARE = 60          # порог в процентах, из наших разборов системы оценки

# кто какой документ спрашивает
WHO = [
    ("Кто принимает", "российский вуз при приёме",
     "китайский вуз, программы обмена, работодатели"),
    ("Что это даёт", "баллы в конкурсе на место",
     "подтверждение уровня владения языком"),
    ("Где сдают", "в школе по месту учёбы", "в экзаменационном центре"),
    ("На каком языке задания и инструкции", "на русском", "на китайском"),
    ("Кто назначает правила", "российская система школьных экзаменов",
     "международный экзаменационный центр"),
]

# три случая: кому что нужно
CASES = [
    ("Поступаю в российский вуз",
     "нужен школьный экзамен",
     "сертификат сам по себе баллов в конкурс не добавляет, но пригодится "
     "на собеседовании и в портфолио"),
    ("Поступаю в китайский вуз",
     "нужен сертификат",
     "школьные баллы там не считают, а аттестат и документы смотрят отдельно"),
    ("Пока не решил",
     "сначала школьный экзамен",
     "его сдают один раз в своё время, а сертификат получают в любой момент"),
]

# что переносится между подготовками, а что нет
OVERLAP = [
    ("Запас слов", "переносится", "общая лексика пригодится и там и там"),
    ("Чтение", "переносится частично",
     "тексты разные по темам, но сам навык один"),
    ("Формат заданий", "не переносится", "каждая сторона задаёт его по-своему"),
    ("Устная часть", "не переносится",
     "у международного экзамена для неё отдельная сдача"),
]

# ----------------------------------------------------------------- проверки
assert LEVELS == 6 and SHARE == 60, "устройство международного экзамена"

assert len(WHO) == 5 and all(len(w) == 3 and all(w) for w in WHO)
assert len(CASES) == 3 and all(len(c) == 3 and all(c) for c in CASES)
assert len(OVERLAP) == 4 and all(len(o) == 3 and all(o) for o in OVERLAP)
assert [o[1] for o in OVERLAP].count("не переносится") == 2, \
    "половина подготовки не переносится"

import re as _re
_TXT = " ".join(x for g in (WHO, CASES, OVERLAP) for t in g for x in t)
# того, чего мы не можем проверить, в данных нет
assert not _re.search(r"ОГЭ|балл\w* \d|\d+\s*балл|\b20\d\d\b|задани\w* \d", _TXT), \
    "чисел школьного экзамена и упоминаний ОГЭ здесь нет"
assert not _re.search(r"соответств", _TXT), \
    "таблица соответствия уровней разобрана у соседа и сюда не идёт"
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
