# -*- coding: utf-8 -*-
"""Данные к статье «HSK 1: что нужно знать».

У каждого требования стоит статус источника. Подтверждённое проверено
несколькими независимыми описаниями, остальное помечено и подаётся
с оговоркой.
"""

CONF = "подтверждено"
DESC = "по описаниям"

# требование, прежняя редакция, действующая, статус
REQS = [
    ("Слов", "150", "300", CONF),
    ("Знаков узнавать", "отдельного требования не было", "около 246", DESC),
    ("Знаков писать от руки", "не требовалось вовсе", "около 100", DESC),
    ("Скорость письма", "не измерялась", "не меньше десяти знаков в минуту", DESC),
    ("Пиньинь над иероглифами", "был", "сохраняется", DESC),
]

# прежняя структура экзамена — она разобрана в соседней статье, здесь только опора
OLD_STRUCT = {"разделов": 2, "вопросов": 40, "максимум": 200, "порог": 120}

# что добавилось к подготовке
NEW_WORK = [
    ("письмо от руки", "навыка не было вовсе: знаки требовалось узнавать, а не писать"),
    ("вдвое больший словарь", "триста слов вместо ста пятидесяти"),
    ("порядок черт", "без него знак пишется неправильно даже при верной форме"),
]

# ----------------------------------------------------------------- расчёты
WORDS_OLD, WORDS_NEW = 150, 300
CHARS_READ, CHARS_WRITE = 246, 100
SPEED = 10

GROWTH = WORDS_NEW // WORDS_OLD
WRITE_SHARE = round(100.0 * CHARS_WRITE / CHARS_READ)
CONFIRMED = [r for r in REQS if r[3] == CONF]
UNCONFIRMED = [r for r in REQS if r[3] == DESC]

# сколько слов в неделю, если готовиться полгода
WEEKS = 26
PER_WEEK = -(-WORDS_NEW // WEEKS)

# ----------------------------------------------------------------- проверки
assert len(REQS) == 5, "требований пять"
assert len(set(r[0] for r in REQS)) == 5, "названия требований не повторяются"
assert all(r[1] and r[2] for r in REQS), "у каждого требования названы обе редакции"
assert all(r[3] in (CONF, DESC) for r in REQS), "у каждого требования есть статус"
assert len(CONFIRMED) == 1 and CONFIRMED[0][0] == "Слов", \
    "подтверждён только словарь, остальное помечено как описания"
assert len(UNCONFIRMED) == 4, "четыре требования идут с оговоркой"

assert WORDS_NEW == 2 * WORDS_OLD and GROWTH == 2, "словарь вырос ровно вдвое"
assert CHARS_WRITE < CHARS_READ, "писать нужно меньше знаков, чем узнавать"
assert 0 < WRITE_SHARE < 100, "доля знаков для письма внутри сотни процентов"
assert SPEED > 0, "скорость письма положительная"

assert OLD_STRUCT["разделов"] == 2 and OLD_STRUCT["вопросов"] == 40, "прежняя структура"
assert OLD_STRUCT["порог"] * 100 // OLD_STRUCT["максимум"] == 60, "порог — три пятых"

assert len(NEW_WORK) == 3 and all(a and b for a, b in NEW_WORK), \
    "у каждой новой работы названо, в чём она состоит"
assert PER_WEEK == 12, "двенадцать слов в неделю за полгода"

# ----------------------------------------------------------------- ход экзамена
# Состав уровней по ДЕЙСТВУЮЩЕЙ редакции. Числа взяты с наших же страниц
# уровней HSK 1—4, где они опубликованы с пометкой «время примерное».
# уровень, разделов, вопросов, минут всего, максимум, порог, минут на письмо
STRUCT = [
    (1, 2,  40,  40, 200, 120, None),
    (2, 2,  60,  55, 200, 120, None),
    (3, 3,  80,  90, 300, 180, 15),
    (4, 3, 100, 105, 300, 180, 25),
]

# словарь на уровнях 1—4: прежняя шкала и действующая (накопительно)
VOCAB = [(1, 150, 300), (2, 300, 500), (3, 600, 1000), (4, 1200, 2000)]

SWITCH = "13 декабря 2026 года"      # глобальный переход на новый стандарт
LAST_OLD = "7 ноября 2026 года"      # последняя обычная сессия уровней 1—6

# что меняется именно в ходе экзамена
COURSE = [
    ("Уровней", "шесть", "девять: три начальных, три средних, три высших", CONF),
    ("Устная часть", "отдельный экзамен", "входит в экзамен с третьего уровня", CONF),
    ("Письмо от руки", "на младших уровнях не требуется", "требуется с первого уровня", CONF),
    ("Время разделов", "известно и опубликовано", "подтверждённых чисел нет", DESC),
]

# время по новому стандарту: подтверждённых чисел нет — и это не заглушка
NEW_TIME = None

# ----------------------------------------------------------------- расчёты хода
LVL = [l for l, *_ in STRUCT]
QUEST = {l: q for l, s, q, m, mx, p, w in STRUCT}
MINUTES = {l: m for l, s, q, m, mx, p, w in STRUCT}
WRITE_MIN = {l: w for l, s, q, m, mx, p, w in STRUCT if w}
# доля письма во всём времени экзамена, в процентах
WRITE_TIME_SHARE = {l: int(round(100.0 * WRITE_MIN[l] / MINUTES[l])) for l in WRITE_MIN}
# во сколько раз четвёртый уровень длиннее первого
LONGER = round(float(MINUTES[4]) / MINUTES[1], 1)
VOCAB_D = {l: (o, n) for l, o, n in VOCAB}

# ----------------------------------------------------------------- проверки хода
assert LVL == [1, 2, 3, 4], "в таблице четыре уровня подряд"
assert all(p * 100 // mx == 60 for l, s, q, m, mx, p, w in STRUCT), \
    "порог везде три пятых от максимума"
assert [s for l, s, q, m, mx, p, w in STRUCT] == [2, 2, 3, 3], \
    "разделов два на младших уровнях и три с третьего"
assert set(WRITE_MIN) == {3, 4}, "письмо есть только на третьем и четвёртом уровнях"
assert all(STRUCT[i][2] < STRUCT[i + 1][2] for i in range(3)), "вопросов становится больше"
assert all(STRUCT[i][3] < STRUCT[i + 1][3] for i in range(3)), "экзамен становится длиннее"
assert all(w < m for l, s, q, m, mx, p, w in STRUCT if w), \
    "письмо занимает часть времени, а не всё"
assert WRITE_TIME_SHARE[4] > WRITE_TIME_SHARE[3], \
    "на четвёртом уровне письму отдана большая доля времени"
assert LONGER > 2, "четвёртый уровень больше чем вдвое длиннее первого"

assert len(VOCAB) == 4 and [l for l, o, n in VOCAB] == LVL, "словарь задан для тех же уровней"
assert all(n > o for l, o, n in VOCAB), "действующий словник тяжелее прежнего на всех четырёх"
assert VOCAB_D[1] == (WORDS_OLD, WORDS_NEW), "первый уровень совпадает с ядром статьи"

assert NEW_TIME is None, "подтверждённого времени по новому стандарту нет и подставлять нечего"
assert len(COURSE) == 4 and sum(1 for *_, st in COURSE if st == CONF) == 3, \
    "три изменения хода подтверждены, четвёртое — отсутствие чисел"
assert COURSE[-1][3] == DESC, "про время разделов подтверждения нет"

import re as _re
_TXT = [x for row in COURSE + NEW_WORK + REQS for x in row if isinstance(x, str)]
_LAT = sorted({w for s in _TXT for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT, "в данных латиница: %s" % _LAT
