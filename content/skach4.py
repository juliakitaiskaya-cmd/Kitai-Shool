# -*- coding: utf-8 -*-
"""Данные к статье «Скачать учебник HSK 4».

Издания новой серии сверены по каталогам магазинов и по публикации
издательства. Страницу каталога издательства целиком открыть не удалось,
поэтому всё, что касается изданий, идёт со статусом «по каталогам»
или «по публикации издательства», а не «подтверждено издателем».
"""

CONF = "подтверждено"
CATAL = "по каталогам магазинов"
PUBL = "по публикации издательства"
DESCR = "по описаниям"
NOCONF = "подтвердить не удалось"

NEW_SERIES = "New HSK Course"
NEW_SERIES_CN = "新HSK教程"
OLD_SERIES = "HSK Standard Course"

VOL_A, VOL_B = "4A", "4B"

# ---------------------------------------------------- комплект прежней серии
# на четвёртом уровне у прежней серии два тома, у каждого тома три книги,
# из них ученику нужны две
OLD_SET = [
    ("Учебник", True, "нужен ученику, и на каждый том свой"),
    ("Рабочая тетрадь", True, "нужна ученику, и на каждый том своя"),
    ("Книга для преподавателя", False, "в наборе есть, но ученику не нужна"),
]
OLD_VOLS = 2

# ---------------------------------------------------- издания новой серии
# что, номер издания, когда вышло, статус
NEW_EDITIONS = [
    ("Учебник, том " + VOL_A, "9787521374445", "сентябрь 2026 года", CATAL),
    ("Учебник, том " + VOL_B, None, "осень 2026 года", PUBL),
    ("Рабочая тетрадь", None, "не издана", CATAL),
]

# уровни, на которых у новой серии тетрадь уже вышла
WB_LEVELS = [1, 2]

# ---------------------------------------------------- три ступени запроса
# что набирают → что есть на бумаге → что есть в электронном виде
STEPS = [
    ("Что набирают",
     "учебник и рабочая тетрадь четвёртого уровня одним файлом",
     4, "четыре книги стоят за словом «учебник» у прежней серии"),
    ("Что есть на бумаге",
     "два учебника новой серии; тетради на этом уровне нет",
     2, "полного комплекта под новый стандарт пока не существует"),
    ("Что есть в электронном виде",
     "звук к урокам и открытые материалы уровня",
     0, "книг целиком не выпускают ни в одной серии"),
]

# ---------------------------------------------------- что бывает в цифре
DIGITAL = [
    ("Сами книги целиком", False, "ни одна серия не издаётся в электронном виде", CONF),
    ("Цифровые материалы новой серии", True,
     "в описаниях изданий обещан доступ к ним, но не к книге", DESCR),
    ("Звук к урокам", True, "код напечатан в самой книге", CONF),
    ("Словник уровня и образцы заданий", True,
     "публикуются вместе с описанием экзамена", CONF),
]

# ---------------------------------------------------- чем закрыть тетрадь
INSTEAD = [
    ("Образцы экзаменационных заданий",
     "формат письменного раздела виден по ним, а не по тетради"),
    ("Тетрадь прежней серии к тому той же буквы",
     "упражнения на лексику совпадают там, где совпадает лексика"),
    ("Свои упражнения на письмо от руки",
     "пятнадцать заданий за двадцать пять минут тренируются только рукой"),
]

# ---------------------------------------------------- расчёты
OLD_FOR_PUPIL = len([n for n, p, w in OLD_SET if p]) * OLD_VOLS      # 4
NEW_TEXTBOOKS = len([e for e in NEW_EDITIONS if e[0].startswith("Учебник")])  # 2
NEW_WORKBOOKS = len([e for e in NEW_EDITIONS
                     if e[0] == "Рабочая тетрадь" and e[2] != "не издана"])   # 0
KNOWN_NUMS = [e[1] for e in NEW_EDITIONS if e[1]]
YES_DIGITAL = [d for d in DIGITAL if d[1]]
NO_DIGITAL = [d for d in DIGITAL if not d[1]]

# ---------------------------------------------------- проверки
assert OLD_FOR_PUPIL == 4, "у прежней серии ученику на уровень нужны четыре книги"
assert OLD_VOLS == 2 and len(OLD_SET) == 3, "два тома, в комплекте тома три книги"
assert len([n for n, p, w in OLD_SET if not p]) == 1, "одна книга комплекта не для ученика"

assert NEW_TEXTBOOKS == 2, "у новой серии на четвёртом уровне два учебника"
assert NEW_WORKBOOKS == 0, "рабочей тетради четвёртого уровня у новой серии нет"
assert len(KNOWN_NUMS) == 1, "подтверждённый номер издания только один"
assert all(len(n) == 13 and n.startswith("978") for n in KNOWN_NUMS), \
    "номер издания записан полностью"
assert NEW_EDITIONS[1][1] is None, "по второму тому номера у нас нет — не выдумываем"
assert NEW_EDITIONS[1][3] == PUBL, "выход второго тома идёт по публикации издательства"
assert 4 not in WB_LEVELS, "четвёртого уровня среди тетрадей новой серии нет"
assert WB_LEVELS == [1, 2], "тетради вышли на первом и втором уровнях"

assert len(STEPS) == 3, "три ступени запроса"
assert [s[2] for s in STEPS] == [4, 2, 0], "ступени сужаются: четыре, две, ноль книг"
assert STEPS[-1][2] == 0, "в электронном виде книг нет — это конец лестницы"

assert len(DIGITAL) == 4 and len(YES_DIGITAL) == 3 and len(NO_DIGITAL) == 1
assert NO_DIGITAL[0][0].startswith("Сами книги"), "книг целиком в цифре нет"
assert sum(1 for d in DIGITAL if d[3] == CONF) == 3, "три строки подтверждены"
assert sum(1 for d in DIGITAL if d[3] == DESCR) == 1, "одна строка идёт по описаниям"

assert len(INSTEAD) == 3 and all(a and b for a, b in INSTEAD), "три замены тетради"

import re as _re
_TXT = " ".join([x for row in NEW_EDITIONS for x in row if isinstance(x, str)]
                + [x for row in DIGITAL for x in row if isinstance(x, str)]
                + [x for row in STEPS for x in row if isinstance(x, str)]
                + [b for a, b in INSTEAD] + [n + " " + w for n, p, w in OLD_SET])
assert not _re.search(r"\bруб|\bцена|\bкупить за|\bюан", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|торрент", _TXT), "адресов и площадок в данных нет"
assert "добор" not in _TXT and "добира" not in _TXT, "жаргона в данных нет"
