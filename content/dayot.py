# -*- coding: utf-8 -*-
"""Данные к статье «Что даёт знание китайского на HSK 4».

Ось узкая и выбрана заказчиком: не «стоит ли учить» и не «зачем учить»
(это две отдельные наши статьи) и не зарплаты (это статья про среднюю
зарплату), а один свободный ключ — что на самом деле даёт четвёртый
уровень.

Сумм и заработков здесь нет по решению заказчика: мы не публикуем
сумм и не выдумываем статистику. Вместо них — от чего зависит оплата
и почему сам уровень её не определяет.

Все числа ниже считаются из словников, разобранных в наших же статьях.
"""

# накопительный объём слов по ступеням
CUR = [300, 500, 1000, 2000, 3600, 5400]     # действующий стандарт
OLD = [150, 300, 600, 1200, 2500, 5000]      # прежний

LEVELS = 6
TARGET = 4            # ступень, о которой статья


def steps(words):
    """Сколько слов прибавляется на каждой ступени."""
    return [words[0]] + [words[i] - words[i - 1] for i in range(1, len(words))]


def share(words, lvl=TARGET):
    """Какая доля всего словаря набрана к этой ступени, в процентах."""
    return 100.0 * words[lvl - 1] / words[-1]


CUR_STEPS = steps(CUR)
OLD_STEPS = steps(OLD)

BY_NUMBER = round(100.0 * TARGET / LEVELS, 1)        # 66,7 — сколько подсказывает номер
BY_WORDS = round(share(CUR), 1)                      # 37,0 — сколько на самом деле
GAP = round(BY_NUMBER - BY_WORDS, 1)                 # 29,7 пункта
BY_WORDS_OLD = round(share(OLD), 1)                  # 24,0

LEFT = CUR[-1] - CUR[TARGET - 1]                     # 3400 слов до шестого
LEFT_TIMES = round(LEFT / float(CUR[TARGET - 1]), 1)  # 1,7 раза
LAST_STEP = CUR_STEPS[-1]                            # 1800
LAST_VS_FOUR = int(round(100.0 * LAST_STEP / CUR[TARGET - 1]))   # 90 %

# что проверяет письменный экзамен, а что остаётся снаружи
COVER = [
    ("Понимание на слух", "да", "раздел экзамена"),
    ("Чтение", "да", "раздел экзамена"),
    ("Письменная речь", "с третьей ступени", "раздел экзамена"),
    ("Устная речь", "нет", "для неё есть отдельный экзамен"),
]

# от чего зависит оплата — вместо сумм
DEPENDS = [
    ("Задача, а не ступень",
     "перевод переписки и переговоры требуют очень разного",
     "ступень говорит о языке, а платят за решённую задачу"),
    ("Вторая специальность",
     "язык плюс закупки, логистика, право или инженерия",
     "чистое знание языка почти всегда стоит меньше связки"),
    ("Устная сторона",
     "письменный сертификат про неё не говорит ничего",
     "её проверяют на собеседовании, и проверяют первой"),
    ("Город и формат работы",
     "удалённо, в поездках или на месте",
     "это меняет условия сильнее, чем номер уровня"),
]

# ----------------------------------------------------------------- проверки
assert len(CUR) == len(OLD) == LEVELS, "шесть ступеней"
assert CUR == sorted(CUR) and OLD == sorted(OLD), "словник растёт"
assert sum(CUR_STEPS) == CUR[-1] and sum(OLD_STEPS) == OLD[-1], "шаги сходятся"

assert BY_NUMBER == 66.7, "номер подсказывает две трети: %s" % BY_NUMBER
assert BY_WORDS == 37.0, "по словам это тридцать семь процентов: %s" % BY_WORDS
assert GAP == 29.7, "разрыв почти тридцать пунктов: %s" % GAP
assert BY_WORDS_OLD == 24.0, "по прежнему словнику ещё меньше: %s" % BY_WORDS_OLD
assert BY_WORDS < BY_NUMBER, "номер уровня завышает пройденный путь"

assert LEFT == 3400, "до шестого ещё три тысячи четыреста слов: %d" % LEFT
assert LEFT_TIMES == 1.7, "это в 1,7 раза больше накопленного: %s" % LEFT_TIMES
assert LAST_STEP == 1800 and LAST_VS_FOUR == 90, \
    "последний шаг почти равен всему пути до четвёртой ступени: %d, %d" % (
        LAST_STEP, LAST_VS_FOUR)
assert CUR_STEPS[-1] > CUR_STEPS[0] * 5, "шаги растут к верху шкалы"

assert len(COVER) == 4 and [c[0] for c in COVER][-1] == "Устная речь"
assert len(DEPENDS) == 4
assert all(len(x) == 3 and all(x) for x in COVER + DEPENDS)

import re as _re
_TXT = " ".join(x for g in (COVER, DEPENDS) for t in g for x in t)
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|\d", _TXT), "сумм и цифр здесь нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
assert not _re.search(r"резюме|intermediate", _TXT), "это темы соседних статей"
