# -*- coding: utf-8 -*-
"""Данные к статье «Бесплатная подготовка к HSK» (разбор по уровням 1–5).

Ось статьи — уровни. Соседняя статья «Бесплатное обучение китайскому
под HSK 3.0» разбирает то же самое по навыкам: лексика, чтение,
аудирование, письмо, произношение. Чтобы страницы не конкурировали,
здесь нет разбора по навыкам, а там нет разбора по уровням.

Числа берутся только те, что уже утверждены в блоге:
  * словник действующего стандарта — накопительно, из данных к статье
    про список слов HSK по уровням;
  * число заданий и разделы — из наших же статей по каждому уровню.
Ничего нового не вписывается: все производные величины считаются.

Чего здесь намеренно нет: сколько образцов заданий выложено на портале
экзамена. Проверить это из рабочей среды нельзя, а пересказывать чужие
описания как свою проверку нечестно — так же решено и в соседней статье.
"""

# ------------------------------------------------- уровень: слова и задания
# (уровень, словник действующего стандарта накопительно, аудирование,
#  чтение, письменная часть, есть ли пиньинь над знаками)
RAW = [
    (1, 300, 20, 20, 0, True),
    (2, 500, 35, 25, 0, True),
    (3, 1000, 40, 30, 10, False),
    (4, 2000, 45, 40, 15, False),
    (5, 3600, 45, 45, 10, False),
]

# прежний стандарт, накопительно — для сверки с теми, кто учил по нему
OLD_WORDS = {1: 150, 2: 300, 3: 600, 4: 1200, 5: 2500}


class Lvl(object):
    def __init__(self, n, words, aud, read, write, pinyin):
        self.n = n
        self.words = words
        self.aud = aud
        self.read = read
        self.write = write
        self.pinyin = pinyin
        self.tasks = aud + read + write
        self.self_check = aud + read          # задания с выбором ответа
        self.share = round(100.0 * self.self_check / self.tasks, 1)
        self.per_task = round(words / float(self.tasks), 1)
        self.old = OLD_WORDS[n]


LEVELS = [Lvl(*r) for r in RAW]
L = {l.n: l for l in LEVELS}

# прибавка уровня: разница с предыдущим
STEPS = []
_prev = 0
for _l in LEVELS:
    STEPS.append((_l.n, _l.words - _prev))
    _prev = _l.words
STEP = dict(STEPS)

MIN_STEP = min(s for n, s in STEPS)
MAX_STEP = max(s for n, s in STEPS)
STEP_TIMES = int(round(MAX_STEP / float(MIN_STEP)))

WORDS_TIMES = int(round(L[5].words / float(L[1].words)))
PER_MIN = min(l.per_task for l in LEVELS)
PER_MAX = max(l.per_task for l in LEVELS)
PER_TIMES = round(PER_MAX / PER_MIN, 1)

SHARE_MIN = min(l.share for l in LEVELS)
SHARE_MAX = max(l.share for l in LEVELS)

# первый уровень, где появляется письменная часть
FIRST_WRITE = min(l.n for l in LEVELS if l.write)
# последний уровень, где над знаками ещё есть пиньинь
LAST_PINYIN = max(l.n for l in LEVELS if l.pinyin)

# ------------------------------------------------- что бесплатно и что нет
# (что это, почему бесплатно, чем это ограничено)
FREE = [
    ("Официальное описание уровня",
     "его публикует сам центр тестирования",
     "это перечень, а не учебник: порядок изучения придётся собрать самому"),
    ("Разбор формата заданий",
     "устройство разделов описано открыто и не меняется от сессии к сессии",
     "понять устройство — не то же, что успеть по времени"),
    ("Словарь и любые тексты своего уровня",
     "словари открыты, а текстов на простом китайском много",
     "подбирать уровень текста придётся на глаз"),
    ("Собственный голос на записи",
     "диктофон есть в любом телефоне",
     "вы слышите то, что хотели сказать, а не то, что сказали"),
]

# (что это, почему бесплатно не выходит)
PAID = [
    ("Регистрация на экзамен", "Взнос платят все, обойти его нельзя."),
    ("Проверка письменной работы", "Свой текст оценить самому нельзя — нужен человек."),
    ("Постановка тонов и звуков", "Ошибку в своём произношении не слышно изнутри."),
]

# ------------------------------------------------- признаки витрины
# (что обещано, что обычно за этим стоит, на что смотреть)
SIGNS = [
    ("курс с нуля до HSK 4 бесплатно",
     "бесплатна начальная часть, а дальше оплата",
     "посмотреть, на каком уроке заканчивается открытый доступ"),
    ("бесплатный доступ навсегда",
     "открыт материал, но закрыта проверка",
     "проверить, можно ли сдать домашнюю работу и получить ответ"),
    ("полный комплект заданий бесплатно",
     "автор сборника не указан",
     "пользоваться как тренажёром, а не как образцом"),
    ("бесплатный урок китайского",
     "это знакомство, а не урок программы",
     "спросить заранее, что будет на нём и что после него"),
]

# ------------------------------------------------- уровень: что с бесплатным
# (уровень, что закрывается бесплатно целиком, где бесплатный путь кончается)
BY_LEVEL = {
    1: ("весь материал уровня — триста слов, два раздела и пиньинь над знаками",
        "ни на чём, бесплатная подготовка здесь доходит до конца"),
    2: ("прибавку в двести слов и те же два раздела",
        "на привычке к скорости, потому что пауз между заданиями становится меньше"),
    3: ("тысячу слов и два раздела из трёх",
        "на письменной части, которую впервые нельзя проверить самому"),
    4: ("прибавку в тысячу слов и разбор новых форматов",
        "на объёме, потому что за одним заданием стоит вдвое больше выученного, чем на третьем"),
    5: ("повторение всего, что уже выучено",
        "на разборе близких по смыслу слов, где сверить себя не с кем"),
}

# ------------------------------------------------- проверки
assert len(LEVELS) == 5, "уровней пять"
assert [l.n for l in LEVELS] == [1, 2, 3, 4, 5], "уровни идут по порядку"
assert [l.words for l in LEVELS] == sorted(l.words for l in LEVELS), \
    "словник растёт от уровня к уровню"
assert L[1].tasks == 40 and L[2].tasks == 60, "задания младших уровней"
assert L[3].tasks == 80 and L[4].tasks == 100 and L[5].tasks == 100, \
    "задания старших уровней"
assert FIRST_WRITE == 3, "письменная часть появляется на третьем уровне"
assert LAST_PINYIN == 2, "пиньинь над знаками держится до второго уровня"
assert WORDS_TIMES == 12, "словник пятого уровня в двенадцать раз больше первого"
assert STEP[1] == 300 and STEP[2] == 200 and STEP[3] == 500, "прибавки младших"
assert STEP[4] == 1000 and STEP[5] == 1600, "прибавки старших"
assert MIN_STEP == 200 and MAX_STEP == 1600 and STEP_TIMES == 8, \
    "самая большая прибавка в восемь раз больше самой маленькой"
assert PER_MIN == 7.5 and PER_MAX == 36.0, "слов на одно задание: крайние значения"
assert PER_TIMES == 4.8, "разница в слогах на задание — почти впятеро"
assert [l.per_task for l in LEVELS] == [7.5, 8.3, 12.5, 20.0, 36.0], \
    "слов на задание посчитано по каждому уровню"
assert SHARE_MIN == 85.0 and SHARE_MAX == 100.0, "доля самопроверяемых заданий"
assert L[3].share == 87.5 and L[5].share == 90.0, "доли третьего и пятого"

assert len(FREE) == 4 and len(PAID) == 3, "четыре бесплатные позиции и три платные"
assert all(len(x) == 3 and all(x) for x in FREE), "у бесплатного есть предел"
assert all(len(x) == 2 and all(x) for x in PAID), "у платного названа причина"
assert all(x[1][0].isupper() and x[1].endswith(".") for x in PAID), \
    "причина платного — отдельное предложение"
assert len(SIGNS) == 4, "четыре обещания с разбором"
assert all(len(x) == 3 and all(x) for x in SIGNS), "у каждого обещания три поля"
assert set(BY_LEVEL) == {1, 2, 3, 4, 5}, "разбор есть на каждом уровне"
assert all(len(v) == 2 and all(v) for v in BY_LEVEL.values()), "два поля на уровень"

import re as _re
_TXT = " ".join(
    [t for x in FREE for t in x] + [t for x in PAID for t in x]
    + [t for x in SIGNS for t in x] + [t for v in BY_LEVEL.values() for t in v])
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|\bцен[аыу]\b", _TXT), \
    "ни сумм, ни цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), \
    "адресов сторонних сайтов в данных нет"
assert not _re.search(r"институт|университет|приложени[ея]\s+[A-ZА-Я]", _TXT, _re.I), \
    "названий площадок и заведений в данных нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
