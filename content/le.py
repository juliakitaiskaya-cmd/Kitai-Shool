# -*- coding: utf-8 -*-
"""Данные к статье «Частица 了 (le) в китайском языке».

PAIRS — пара «без частицы / с частицей»: фраза, пиньинь, перевод для обеих
сторон и подпись, что частица добавила.
TIMELINE — три точки оси времени: маркер, фраза, пиньинь, перевод, роль 了.
"""

ROLES = ("завершённость действия", "изменение ситуации")

PAIRS = [
    ("我买书", "wǒ mǎi shū", "я покупаю книги",
     "我买了一本书", "wǒ mǎi le yì běn shū", "я купил книгу",
     "завершённость действия"),
    ("下雨", "xià yǔ", "идёт дождь",
     "下雨了", "xià yǔ le", "пошёл дождь",
     "изменение ситуации"),
    ("我饿", "wǒ è", "я голоден",
     "我饿了", "wǒ è le", "я проголодался",
     "изменение ситуации"),
]

TIMELINE = [
    ("вчера", "昨天我买了一本书", "zuótiān wǒ mǎi le yì běn shū",
     "вчера я купил книгу", "завершённость действия"),
    ("сейчас", "下雨了", "xià yǔ le",
     "пошёл дождь", "изменение ситуации"),
    ("завтра", "明天我就回家了", "míngtiān wǒ jiù huí jiā le",
     "завтра я уже еду домой", "изменение ситуации"),
]

NO_LE = [
    ("привычное и регулярное", "我每天七点起床", "wǒ měi tiān qī diǎn qǐ chuáng",
     "я каждый день встаю в семь"),
    ("отрицание через 没", "我没买书", "wǒ méi mǎi shū", "я не купил книгу"),
    ("глаголы состояния", "我认识他", "wǒ rènshi tā", "я с ним знаком"),
]

DOUBLE = ("我学了三年了", "wǒ xué le sān nián le",
          "я учу уже три года — и продолжаю")

# ----------------------------------------------------------------- проверки
assert len(PAIRS) == 3, "пар «без частицы / с частицей» ровно три"
for a, apy, atr, b, bpy, btr, role in PAIRS:
    assert "了" not in a, "в левой фразе частицы нет: %s" % a
    assert "了" in b, "в правой фразе частица стоит: %s" % b
    assert atr != btr, "переводы сторон должны различаться: %s" % a
    assert role in ROLES, "роль берётся из закрытого набора: %s" % role
    assert b.startswith(a[:2]), "правая фраза строится из левой: %s / %s" % (a, b)

assert len(TIMELINE) == 3, "точек на оси времени три"
assert len(set(t[0] for t in TIMELINE)) == 3, "маркеры времени не повторяются"
for mark, ex, py, tr, role in TIMELINE:
    assert "了" in ex, "на каждой точке оси частица стоит: %s" % mark
    assert role in ROLES, "роль берётся из закрытого набора: %s" % role
assert "завтра" in [t[0] for t in TIMELINE], \
    "будущее на оси обязательно — иначе разговор о «прошедшем времени» не закрыт"

assert len(NO_LE) == 3, "случаев без частицы три"
assert all("了" not in n[1] for n in NO_LE), "в примерах без частицы её нет"
assert DOUBLE[0].count("了") == 2, "в двойном примере частица стоит дважды"
