# -*- coding: utf-8 -*-
"""Данные к статье «Сколько готовиться к HSK».

Ось статьи — расстояние между тем уровнем, который у человека есть,
и тем, который он хочет сдать. Опубликованные соседи отвечают на другой
вопрос — «за сколько выучить язык с нуля до уровня» — и дают сроки
в месяцах и часах. Чтобы страницы не конкурировали, здесь нет ни сроков
с нуля в месяцах, ни часов на уровень, ни оценок FSI: всё это остаётся
у соседей и отдаётся ссылками.

Числа берутся только утверждённые в блоге: словник по уровням
действующего и прежнего стандарта. Всё остальное считается.

Чего здесь намеренно нет: минут и секунд на одно задание — это разобрано
в нашей статье про длительность экзамена, и повторять её нельзя.
"""

# уровень → словник накопительно, действующий стандарт
NEW = {0: 0, 1: 300, 2: 500, 3: 1000, 4: 2000, 5: 3600}
# уровень → словник накопительно, прежний стандарт
OLD = {0: 0, 1: 150, 2: 300, 3: 600, 4: 1200, 5: 2500}

LEVELS = [0, 1, 2, 3, 4, 5]


def gap(start, goal, table=NEW):
    """Сколько слов выучить от одного уровня до другого."""
    assert start < goal, "цель должна быть выше старта"
    return table[goal] - table[start]


# матрица «откуда → куда»: сколько слов выучить
MATRIX = {(a, b): gap(a, b) for a in LEVELS for b in LEVELS if a < b}

# сроки, в днях
SPANS = [("два месяца", 60), ("три месяца", 90), ("полгода", 180),
         ("год", 365), ("два года", 730)]
SPAN_D = dict(SPANS)


def per_day(start, goal, span):
    return round(gap(start, goal) / float(SPAN_D[span]), 1)


# пять вопросов брифа, посчитанные
# (как звучит вопрос, старт, цель, срок, слов в день)
CASES = [
    ("с нуля до HSK 4 за два года", 0, 4, "два года"),
    ("с нуля до HSK 4 за год", 0, 4, "год"),
    ("с HSK 3 до HSK 4 за год", 3, 4, "год"),
    ("с HSK 2 до HSK 3 за два месяца", 2, 3, "два месяца"),
    ("с нуля до HSK 3 за два месяца", 0, 3, "два месяца"),
]
CASE_ROWS = [(name, a, b, span, gap(a, b), per_day(a, b, span))
             for name, a, b, span in CASES]

# два сценария с одинаковой дневной нормой — главный разворот
SAME = [c for c in CASE_ROWS if c[5] == 2.7]

# во сколько раз цель «тяжелее» при старте с нуля, чем от соседнего уровня
TIMES_3 = round(gap(0, 3) / float(gap(2, 3)), 1)
TIMES_4 = round(gap(0, 4) / float(gap(3, 4)), 1)

# насколько действующий словник тяжелее прежнего на третьем и четвёртом
HARDER_3 = round(NEW[3] / float(OLD[3]), 1)
HARDER_4 = round(NEW[4] / float(OLD[4]), 1)

# столбец «до HSK 3» и «до HSK 4» от каждого старта
TO_3 = [(a, gap(a, 3)) for a in (0, 1, 2)]
TO_4 = [(a, gap(a, 4)) for a in (0, 1, 2, 3)]

# что ещё входит в подготовку, кроме слов
# (что это, как это считается, почему это не месяцы)
PARTS = [
    ("Недостающие слова",
     "разница между словником вашего уровня и словником цели",
     "единственная часть, которую можно посчитать заранее"),
    ("Проверка стартового уровня",
     "один прогон по заданиям уровня, который вы считаете своим",
     "без него план считается от выдуманной точки"),
    ("Привычка к формату",
     "несколько полных прогонов по времени",
     "занимает недели, а не месяцы, и почти не зависит от уровня"),
    ("Письменная часть",
     "появляется с третьего уровня и тренируется отдельно",
     "её нельзя проверить самому, и это отдельная строка плана"),
]

# почему в сети встречаются более короткие сроки
# (что обычно написано, в чём подвох)
WHY_SHORT = [
    ("«до HSK 4 за год»",
     "срок посчитан по прежнему словнику, где до четвёртого уровня было "
     "вдвое меньше слов"),
    ("«HSK 3 за два месяца»",
     "почти всегда имеется в виду старт не с нуля, а со второго уровня"),
    ("«уровень за месяц»",
     "считается только лексика, без формата, скорости и письменной части"),
]

# что делать, если срок не сходится
# (решение, что оно даёт, чем расплачиваешься)
IF_SHORT = [
    ("Сдвинуть дату на следующую сессию",
     "срок растягивается, дневная норма падает",
     "ждать придётся несколько месяцев: сессий в году немного"),
    ("Сдавать уровень ниже",
     "цель становится достижимой в тот же срок",
     "сертификат будет на уровень ниже, чем хотелось"),
    ("Поднять дневную норму",
     "срок остаётся прежним",
     "работает не у всех и только на коротком отрезке"),
]

# ----------------------------------------------------------------- проверки
assert NEW[5] == 3600 and OLD[5] == 2500, "словники обоих стандартов"
assert gap(0, 1) == 300 and gap(1, 2) == 200 and gap(2, 3) == 500, "соседние переходы"
assert gap(3, 4) == 1000 and gap(4, 5) == 1600, "старшие переходы"
assert gap(0, 3) == 1000 and gap(0, 4) == 2000, "переходы с нуля"
assert gap(2, 4) == 1500 and gap(1, 3) == 700, "переходы через ступень"
assert len(MATRIX) == 15, "в треугольной матрице пятнадцать клеток"

assert len(CASE_ROWS) == 5, "пять вопросов брифа посчитаны"
assert [c[5] for c in CASE_ROWS] == [2.7, 5.5, 2.7, 8.3, 16.7], \
    "дневные нормы посчитаны: %s" % [c[5] for c in CASE_ROWS]
assert len(SAME) == 2, "два сценария дают одну и ту же дневную норму"
assert SAME[0][1] == 0 and SAME[0][2] == 4 and SAME[1][1] == 3, \
    "совпадают «с нуля до HSK 4 за два года» и «с HSK 3 до HSK 4 за год»"

assert TIMES_3 == 2.0 and TIMES_4 == 2.0, "с нуля вдвое дальше, чем от соседнего уровня"
assert HARDER_3 == 1.7 and HARDER_4 == 1.7, "действующий словник тяжелее прежнего"
assert [w for a, w in TO_3] == [1000, 700, 500], "столбец до третьего уровня"
assert [w for a, w in TO_4] == [2000, 1700, 1500, 1000], "столбец до четвёртого"

assert len(PARTS) == 4 and all(len(x) == 3 and all(x) for x in PARTS), "четыре части"
assert len(WHY_SHORT) == 3 and all(len(x) == 2 and all(x) for x in WHY_SHORT)
assert len(IF_SHORT) == 3 and all(len(x) == 3 and all(x) for x in IF_SHORT)

import re as _re
_TXT = " ".join([t for x in PARTS for t in x] + [t for x in WHY_SHORT for t in x]
                + [t for x in IF_SHORT for t in x])
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥", _TXT), "сумм в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов в данных нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"час(?:ов|а)\b|FSI", _TXT), \
    "часы и оценки FSI остаются у соседей"
