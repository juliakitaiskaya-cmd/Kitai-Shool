# -*- coding: utf-8 -*-
"""Данные к статье «Учебник HSK 3».

None означает, что цифру подтвердить не удалось. Прибавки по уровням
считаются из накопительных шкал, а не вписываются руками.
"""

CONF = "подтверждено"
OURS = "наш расчёт"
DESC = "по описаниям"

VOL_TAG = "3"
LESSONS = 20            # уроков в томе — число сошлось в нескольких описаниях
VOL_WORDS = None        # слов в томе — подтвердить не удалось
LESSONS_FIRST = 15      # уроков в томе первого уровня, для сравнения

# накопительные словники: уровень → (прежний, действующий)
SCALE = {1: (150, 300), 2: (300, 500), 3: (600, 1000)}

# экзамен третьего уровня по действующей редакции
EXAM = {"разделов": 3, "вопросов": 80, "минут": 90, "максимум": 300, "порог": 180,
        "письмо_заданий": 10, "письмо_минут": 15}

SWITCH = "13 декабря 2026 года"
SPEAKING_FROM = 3       # уровень, с которого устная часть входит внутрь экзамена

# что проверяет экзамен третьего уровня и есть ли это в комплекте тома
MATRIX = [
    ("Чтение без пиньиня", True, "тексты урока идут уже без транскрипции"),
    ("Письмо: собрать предложение и написать знак", True,
     "такие задания есть в рабочей тетради"),
    ("Устная часть внутри экзамена", False,
     "в комплекте тома её не тренирует ни одна из трёх книг"),
]

# ----------------------------------------------------------------- расчёты
def steps(idx):
    out, prev = {}, 0
    for lvl in sorted(SCALE):
        total = SCALE[lvl][idx]
        out[lvl] = total - prev
        prev = total
    return out


STEP_OLD = steps(0)          # прибавка на уровне по прежней шкале
STEP_NEW = steps(1)          # прибавка на уровне по действующей
LEVEL_NEW = SCALE[3][1]
LEVEL_OLD = SCALE[3][0]
COVER = round(100.0 * LEVEL_OLD / LEVEL_NEW)
REST = LEVEL_NEW - LEVEL_OLD
TWO_FIRST = STEP_NEW[1] + STEP_NEW[2]        # прибавка первых двух уровней вместе
RATIO = round(float(LEVEL_NEW) / LEVEL_OLD, 2)
MORE_LESSONS = LESSONS - LESSONS_FIRST

# ----------------------------------------------------------------- проверки
assert LESSONS == 20 and LESSONS > LESSONS_FIRST, "том третьего уровня длиннее первого"
assert MORE_LESSONS == 5, "на пять уроков больше, чем в первом томе"
assert VOL_WORDS is None, "слов в томе третьего уровня подтвердить не удалось"

assert STEP_NEW == {1: 300, 2: 200, 3: 500}, "прибавки по действующей шкале"
assert STEP_OLD == {1: 150, 2: 150, 3: 300}, "прибавки по прежней шкале"
assert STEP_NEW[3] == TWO_FIRST == 500, \
    "на третьем уровне добавляется столько же слов, сколько на первых двух вместе"
assert STEP_NEW[3] > STEP_NEW[1] > STEP_NEW[2], "третий уровень — самый тяжёлый из младших"
assert STEP_NEW[3] == 2 * STEP_OLD[3] - 100, "прибавка выросла против прежней шкалы"
assert COVER == 60 and REST == 400, "том закрывает три пятых, добрать четыреста"
assert RATIO == 1.67, "разрыв шкал на третьем уровне такой же, как на втором"

assert EXAM["разделов"] == 3 and EXAM["вопросов"] == 80, "структура третьего уровня"
assert EXAM["порог"] * 100 // EXAM["максимум"] == 60, "порог — три пятых"
assert EXAM["письмо_заданий"] == 10 and EXAM["письмо_минут"] == 15, "письменный раздел"
assert SPEAKING_FROM == 3, "устная часть входит в экзамен с третьего уровня"

assert len(MATRIX) == 3, "в матрице три строки"
assert sum(1 for n, yes, c in MATRIX if yes) == 2, "две строки книга закрывает, одну нет"
assert MATRIX[-1][1] is False and "устн" in MATRIX[-1][0].lower(), \
    "не закрыта именно устная часть"

import re as _re
_TXT = [x for row in MATRIX for x in row if isinstance(x, str)] + [SWITCH]
_LAT = sorted({w for s in _TXT for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT, "в данных латиница: %s" % _LAT
