# -*- coding: utf-8 -*-
"""Данные к статье «Бесплатное обучение китайскому под HSK 3.0».

SKILLS — навык, докуда дотягивает бесплатная работа (доля), чем закрывается
бесплатно, где упирается.
GATES — платные шлюзы на пути к сертификату.
"""

FREE, PART, PAID = "полностью", "частично", "нет"
STATES = (FREE, PART, PAID)

SKILLS = [
    ("Лексика", 95, FREE,
     "списки слов, карточки, повторение по расписанию",
     "почти ни во что: слово либо узнаётся, либо нет, и это видно самому"),
    ("Чтение", 85, FREE,
     "тексты своего уровня и разбор со словарём",
     "в скорость: без замера легко застрять на комфортном темпе"),
    ("Аудирование", 70, PART,
     "записи, подкасты, повторное прослушивание знакомого",
     "в разбор ошибки: непонятое место сам себе не объяснишь"),
    ("Формат экзамена", 60, PART,
     "образцы заданий и прогоны по времени",
     "в количество: образцов меньше, чем нужно для привыкания"),
    ("Письменная часть", 25, PAID,
     "образцы и чужие проверенные работы",
     "в проверку: свою письменную работу оценить самому нельзя"),
    ("Произношение", 15, PAID,
     "запись себя на диктофон и сравнение с эталоном",
     "в собственное ухо: вы слышите то, что хотели сказать"),
]

GATES = [
    ("регистрация на экзамен", "платная всегда", "обойти нельзя"),
    ("пересдача", "оплачивается заново", "обойти нельзя"),
    ("проверка письменной части до экзамена", "нужен человек", "можно заменить обменом работами"),
    ("постановка звука", "нужен человек", "обойти нельзя"),
]

CAUTION = [
    ("списки лексики из сети", "встречаются народные версии, собранные читателями",
     "сверять с официальным описанием уровня"),
    ("готовые «полные» наборы заданий", "их авторство обычно не указано",
     "использовать как тренажёр, а не как эталон"),
    ("курсы «бесплатно навсегда»", "обычно бесплатна только первая часть",
     "смотреть, где начинается оплата"),
]

# ----------------------------------------------------------------- проверки
assert len(SKILLS) == 6, "навыков шесть"
assert len(set(s[0] for s in SKILLS)) == 6, "навыки не повторяются"
for name, pct, state, how, limit in SKILLS:
    assert 0 < pct <= 100, "доля в процентах: %s" % name
    assert state in STATES, "состояние из закрытого набора: %s" % name
    assert how and limit, "у каждого навыка сказано, чем закрывается и где упирается: %s" % name

PCTS = [s[1] for s in SKILLS]
assert PCTS == sorted(PCTS, reverse=True), "навыки идут от самого доступного к самому закрытому"
assert SKILLS[0][2] == FREE and SKILLS[-1][2] == PAID, "крайние случаи — разные"
BY_STATE = {st: [s[0] for s in SKILLS if s[2] == st] for st in STATES}
assert len(BY_STATE[FREE]) == 2 and len(BY_STATE[PART]) == 2 and len(BY_STATE[PAID]) == 2, \
    "по два навыка в каждом состоянии"

assert len(GATES) == 4, "платных шлюзов четыре"
HARD = [g for g in GATES if g[2] == "обойти нельзя"]
assert len(HARD) == 3, "три шлюза непреодолимы"
assert any("регистрация" in g[0] for g in GATES), "платная регистрация названа"

assert len(CAUTION) == 3, "предостережений три"
assert all(len(c) == 3 and all(c) for c in CAUTION), "у каждого есть что, почему и что делать"
