# -*- coding: utf-8 -*-
"""Данные к переработке статьи «Стипендия CSC».

Новую страницу по этому брифу не делаем: тема закрыта шестью нашими
статьями, а присланный тайтл почти дословно совпадает с существующей
«Стипендия CSC в Китае». Вместо седьмой страницы переписываем эту —
она не опубликована, в ней 10 480 знаков вместо нормы и она написана
по прежним правилам: с суммами в юанях, ссылками на сторонние сайты
и хештегами. Сейчас она не прошла бы наши собственные проверки.

Что уходит при переработке: суммы, внешние ссылки, хештеги, возрастные
ориентиры и месяцы подачи — всё это либо запрещено нашими правилами,
либо меняется от года к году и от вуза к вузу.

Что добавляется: два свободных ключа брифа — как выбрать вуз под
заявку и чем провинциальные гранты отличаются от правительственного.
"""

# три канала подачи — порядок из нашей же прежней версии
CHANNELS = [
    ("Через посольство", "двусторонняя программа между странами",
     "отбор централизованный, у канала своя очередь и свои сроки"),
    ("Через университет", "напрямую в приёмную комиссию вуза",
     "вуз сам выдвигает кандидата, и это самый частый путь"),
    ("Через провинцию и отдельные программы", "региональные наборы",
     "свои условия и свой список участвующих вузов"),
]

# что покрывает полная стипендия — без сумм, это решение по правилам
COVER = [
    ("Обучение", "да", "плата за программу не вносится"),
    ("Проживание", "обычно да", "место в общежитии или доплата на жильё"),
    ("Ежемесячное содержание", "да", "размер зависит от ступени и года"),
    ("Медицинская страховка", "да", "базовая, для иностранных студентов"),
    ("Дорога и бытовые расходы", "нет", "это остаётся на вас"),
]

# цепочка: подача — последний шаг, а не первый
CHAIN = [
    ("Выбрать направление и программу", "без этого остальное бессмысленно"),
    ("Найти вуз, где это направление сильное", "и проверить, участвует ли он"),
    ("Написать научному руководителю", "и получить предварительное согласие"),
    ("Собрать документы", "часть из них делается дольше всего"),
    ("Написать план обучения под эту программу", "ключевой документ заявки"),
    ("Пройти номинацию", "вуз или посольство выдвигает кандидата"),
    ("Подать заявку", "последний шаг, а не первый"),
]

# как выбирать вуз под заявку — четыре признака
PICK = [
    ("Участвует ли вуз в программе",
     "списки участников пересматриваются, и прошлогодний не годится"),
    ("Есть ли там ваше направление как сильное",
     "заявка в слабую для вуза область читается как случайная"),
    ("Есть ли научный руководитель по вашей теме",
     "без конкретного человека план обучения получается общим"),
    ("На каком языке идёт программа",
     "от этого зависит, какой языковой документ от вас ждут"),
]

# три уровня: кто даёт деньги
LEVELS = [
    ("Правительственный", "общенациональная программа",
     "самый известный и самый конкурсный уровень"),
    ("Провинциальный", "программы отдельных регионов",
     "меньше известности, другой круг участников"),
    ("Университетский", "собственные стипендии вузов",
     "условия вуз устанавливает сам и меняет чаще всего"),
]

# ----------------------------------------------------------------- проверки
assert len(CHANNELS) == 3 and all(len(c) == 3 and all(c) for c in CHANNELS)
assert len(COVER) == 5 and all(len(c) == 3 and all(c) for c in COVER)
assert [c[1] for c in COVER].count("нет") == 1, "одна строка покрытия отрицательная"
assert len(CHAIN) == 7 and all(len(c) == 2 and all(c) for c in CHAIN)
assert CHAIN[-1][0] == "Подать заявку", "подача стоит последней"
assert len(PICK) == 4 and all(len(p) == 2 and all(p) for p in PICK)
assert len(LEVELS) == 3 and all(len(x) == 3 and all(x) for x in LEVELS)

import re as _re
_TXT = " ".join(x for g in (CHANNELS, COVER, CHAIN, PICK, LEVELS)
                for t in g for x in t)
# сумм, дат, возрастов и названий здесь нет — это решение по правилам
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|\d", _TXT), \
    "сумм, возрастов и чисел в этих данных нет"
assert not _re.search(r"Циндао|Пекин|Шанхай|университет\s+[А-ЯA-Z]", _TXT), \
    "названий городов и вузов не называем"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
