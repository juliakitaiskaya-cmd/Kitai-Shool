# -*- coding: utf-8 -*-
"""Данные к статье «Можно ли сдать HSK онлайн».

Всё, что касается домашнего формата, идёт по описаниям порядка записи.
Объявления экзамена я не открывала, доступность формата в России
подтвердить не удалось, поэтому статусы проставлены у каждой строки.
"""

DESCR = "по описаниям порядка записи"
ONE = "в одном источнике, не подтверждено"
SPLIT = "источники называют разное"
NOCONF = "подтвердить не удалось"

# ---------------------------------------------- три условия, от которых зависит ответ
CONDS = [
    ("Уровень", "домашний формат есть не для всех уровней", DESCR),
    ("Дата", "он открыт не на каждую сессию, а на часть дат", DESCR),
    ("Страна", "сдавать можно только там, где вы записались", DESCR),
]

TOP_BAND = "7–9"          # верхняя ступень — только в центре
TOP_ONLY_CENTER = True

# ---------------------------------------------- что нужно для записи
NEEDED = [
    ("Фотография", True, "нужна для любого уровня и любого формата", DESCR),
    ("Документ при записи у себя в стране", True,
     "подходит внутреннее удостоверение, паспорт тоже", DESCR),
    ("Документ при записи за её пределами", True, "здесь нужен именно паспорт", DESCR),
    ("Запись на устную часть", True,
     "на части уровней её оформляют вместе с письменной", ONE),
]

# ---------------------------------------------- сроки закрытия записи
DEADLINES = [(7, 10, "по компьютерному формату"), (10, 10, "по тому же формату"),
             (14, 14, "по верхней ступени")]
DEADLINE_MIN = min(a for a, b, w in DEADLINES)
DEADLINE_MAX = max(b for a, b, w in DEADLINES)

# ---------------------------------------------- чего подтвердить не удалось
UNKNOWN = [
    ("Требования к комнате и технике",
     "в открытых описаниях порядка записи их нет вовсе"),
    ("Доступность домашнего формата в России",
     "объявления, где это сказано прямо, я не нашла"),
    ("Как именно идёт наблюдение",
     "описания расходятся, а проверить их не по чему"),
]

# ---------------------------------------------- расчёты
COND_N = len(CONDS)
YOURS = 0                  # сколько из трёх условий зависит от сдающего
DEADLINE_SPREAD = DEADLINE_MAX - DEADLINE_MIN

# ---------------------------------------------- проверки
assert COND_N == 3 and all(a and b for a, b, s in CONDS)
assert all(s == DESCR for a, b, s in CONDS), "все три условия идут с одной оговоркой"
assert YOURS == 0, "ни одно из трёх условий не зависит от сдающего — это и есть находка"
assert TOP_ONLY_CENTER and TOP_BAND == "7–9", "верхняя ступень сдаётся только в центре"

assert len(NEEDED) == 4 and sum(1 for n, y, w, s in NEEDED if s == ONE) == 1
assert all(y for n, y, w, s in NEEDED), "перечень того, что нужно, а не чего не нужно"

assert DEADLINE_MIN == 7 and DEADLINE_MAX == 14, "разброс сроков записи"
assert DEADLINE_SPREAD == 7, "разброс ровно в неделю"

assert len(UNKNOWN) == 3 and all(a and b for a, b in UNKNOWN)

import re as _re
_TXT = " ".join([a + " " + b for a, b, s in CONDS] + [n + " " + w for n, y, w, s in NEEDED]
                + [a + " " + b for a, b in UNKNOWN])
assert not _re.search(r"\bруб|\bцена|\bстоимость|\bюан", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|chinesetest", _TXT), "адресов сайтов в данных нет"
assert not _re.search(r"университет|институт|центр [А-ЯЁ]", _TXT), \
    "названий вузов и центров в данных нет"
assert not _re.search(r"добор|добира|добрат", _TXT), "жаргона в данных нет"
