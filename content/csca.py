# -*- coding: utf-8 -*-
"""Данные к статье «CSCA: что сдавать и как готовиться».

SUBJECTS — предмет, китайское название, вопросов, минут, язык сдачи, статус.
TRACKS — кому какой набор предметов.
EXEMPT — кто освобождён и от чего.
"""

SUBJECTS = [
    ("Профессиональный китайский", "专业汉语", 80, 90, "только китайский",
     "обязателен для программ на китайском"),
    ("Математика", "数学", 48, 60, "китайский или английский",
     "обязательна почти всем"),
    ("Физика", "物理", 48, 60, "китайский или английский",
     "по выбору — зависит от специальности"),
    ("Химия", "化学", 48, 60, "китайский или английский",
     "по выбору — зависит от специальности"),
]

SCORE_MAX = 100

TRACKS = [
    ("программа на китайском, STEM",
     ("专业汉语 — направление STEM", "数学", "物理 или 化学 — по требованию вуза")),
    ("программа на китайском, гуманитарная",
     ("专业汉语 — гуманитарное направление", "数学")),
    ("программа на английском",
     ("数学", "物理 или 化学 — по требованию вуза")),
]

EXEMPT = [
    ("программы на английском", "языковую часть не сдают", "подтверждено"),
    ("выпускники подготовительных факультетов при вузах — участниках программы "
     "правительственных стипендий", "экзамен не сдают вовсе", "подтверждено"),
    ("абитуриенты на китайскую филологию и смежные специальности",
     "от языковой части могут освободить", "условия в описаниях не раскрыты"),
]

DISPUTED = ("число вопросов в языковой части",
            "в большинстве описаний 80, в отдельных — около ста")

# ----------------------------------------------------------------- проверки
assert len(SUBJECTS) == 4, "предметов четыре"
assert len(set(s[0] for s in SUBJECTS)) == 4, "предметы не повторяются"

LANG = SUBJECTS[0]
SCI = SUBJECTS[1:]
assert LANG[4] == "только китайский", "языковую часть сдают лишь по-китайски"
assert all(s[4] == "китайский или английский" for s in SCI), \
    "естественнонаучные предметы сдают на выбор"
assert all(s[2] == 48 and s[3] == 60 for s in SCI), \
    "у естественнонаучных предметов одинаковый формат"
assert LANG[2] != SCI[0][2] and LANG[3] != SCI[0][3], \
    "формат языковой части отличается от предметной"

# секунды на вопрос — считаются, а не вписываются руками
SEC = {name: round(60.0 * mins / q) for name, cn, q, mins, lang, st in SUBJECTS}
assert SEC["Профессиональный китайский"] < SEC["Математика"], \
    "на языковой части времени на вопрос меньше — это и есть главная находка"

assert len(TRACKS) == 3 and len(set(t[0] for t in TRACKS)) == 3
for name, items in TRACKS:
    assert 2 <= len(items) <= 3, "в наборе два или три предмета: %s" % name
ENG = [t for t in TRACKS if "английском" in t[0]]
assert len(ENG) == 1 and not any("汉语" in i for i in ENG[0][1]), \
    "в англоязычной программе языковой части нет"

assert len(EXEMPT) == 3, "случаев освобождения три"
UNSURE = [e for e in EXEMPT if e[2] != "подтверждено"]
assert len(UNSURE) == 1, "неуверенный случай ровно один"
assert "не раскрыт" in UNSURE[0][2], "у неуверенного случая стоит пометка"

assert SCORE_MAX == 100
assert DISPUTED[0] and "80" in DISPUTED[1], "расхождение названо прямо"
