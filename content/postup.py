# -*- coding: utf-8 -*-
"""Данные к статье «Какой уровень HSK нужен для поступления».

Сводка по ступеням в одном месте. Своего материала о требованиях
конкретных вузов у меня нет и выдумывать его нельзя, поэтому все
утверждения — из наших же статей, а формулировки соседей не копируются.

Числа словника — из данных к разбору списка слов HSK по уровням.
Всё остальное считается.
"""

HSK, ENG, NONE = "HSK", "международный сертификат по английскому", "языкового экзамена нет"

# словник действующего стандарта, накопительно
WORDS = {1: 300, 2: 500, 3: 1000, 4: 2000, 5: 3600, 6: 5400}

# (ступень, какой экзамен, уровень, что это значит на практике)
STAGES = [
    ("Языковой год и курсы", NONE, None,
     "на вход экзамен обычно не нужен: за ним как раз и едут"),
    ("Бакалавриат на китайском", HSK, 4,
     "порог допуска к программе, а не уровень комфорта на лекциях"),
    ("Более требовательные программы", HSK, 5,
     "та же ступень обучения, но планка выше"),
    ("Магистратура на китайском", HSK, 5,
     "сертификат открывает дверь, а язык учёбы осваивается отдельно"),
    ("Программы на английском", ENG, None,
     "вместо HSK подтверждают английский, и порог ставит сама программа"),
]

# что считается отдельно от допуска
EXTRA = [
    ("Освобождение от первого курса языковой подготовки", 6, 180,
     "отдельная возможность, а не требование к поступлению"),
]

# три вещи, которые сертификат не закрывает (по нашей статье о магистратуре)
GAPS = [
    ("Процедурный язык", "оформление, печати, регистрация"),
    ("Социальный язык", "обращения внутри кафедры и курса"),
    ("Академический язык", "защита, проверка работы, научный текст"),
]

# ----------------------------------------------------------------- расчёты
HSK_STAGES = [s for s in STAGES if s[1] == HSK]
NO_HSK = [s for s in STAGES if s[1] != HSK]
LEVELS_ASKED = sorted({s[2] for s in STAGES if s[2]})
LOW, HIGH = min(LEVELS_ASKED), max(LEVELS_ASKED)

WORDS_LOW, WORDS_HIGH = WORDS[LOW], WORDS[HIGH]
STEP_UP = WORDS_HIGH - WORDS_LOW          # сколько слов между четвёртым и пятым
SHARE = round(100.0 * STEP_UP / WORDS_LOW)  # прибавка в процентах от всего пути до LOW

FREE_LEVEL = WORDS[EXTRA[0][1]]
FREE_STEP = FREE_LEVEL - WORDS_HIGH

# ----------------------------------------------------------------- проверки
assert len(STAGES) == 5, "ступеней пять"
assert all(len(s) == 4 for s in STAGES), "у ступени четыре поля"
assert len(HSK_STAGES) == 3 and len(NO_HSK) == 2, \
    "HSK нужен на трёх ступенях из пяти, на двух — нет"
assert LEVELS_ASKED == [4, 5], "просят четвёртый и пятый уровни"
assert LOW == 4 and HIGH == 5
assert WORDS_LOW == 2000 and WORDS_HIGH == 3600, "словник четвёртого и пятого"
assert STEP_UP == 1600, "между четвёртым и пятым тысяча шестьсот слов"
assert SHARE == 80, "прибавка равна восьмидесяти процентам всего пути до четвёртого"
assert FREE_LEVEL == 5400 and FREE_STEP == 1800, "шестой уровень и шаг до него"
assert EXTRA[0][2] == 180, "порог освобождения от первого курса"

assert len(GAPS) == 3 and all(len(g) == 2 and all(g) for g in GAPS), "три разрыва"
assert NO_HSK[0][1] == NONE and NO_HSK[1][1] == ENG, \
    "две ступени без HSK: языковой год и программы на английском"

import re as _re
_TXT = " ".join([str(x) for s in STAGES for x in s if isinstance(x, str)]
                + [x for g in GAPS for x in g]
                + [e[3] for e in EXTRA])
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|заказать|купить", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"университет[а-я]* [А-ЯЁ]|институт[а-я]* [А-ЯЁ]", _TXT), \
    "названий вузов нет"
assert not _re.search(r"сильные вузы и популярн", _TXT), \
    "формулировка соседа не копируется"
