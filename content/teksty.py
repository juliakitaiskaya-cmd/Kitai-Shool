# -*- coding: utf-8 -*-
"""Данные к статье «Тексты для HSK: как выбрать свой уровень».

Доли покрытия взяты из исследований по чтению на иностранном языке.
Они получены на английском материале, и перенос на китайский — наше
допущение, которое в тексте названо прямо.
"""

CONF = "подтверждено"
OURS = "наш вывод"

# доля знакомых слов, что с таким текстом происходит, сколько незнакомых на сто слов
COVERAGE = [
    (98, "читается свободно, словарь нужен изредка", 2, CONF),
    (95, "читается с опорой: словарь под рукой", 5, CONF),
    (90, "это уже разбор, а не чтение", 10, OURS),
]

# три прохода по одному тексту
PASSES = [
    ("первый", "прочитать целиком, не останавливаясь",
     "понять, о чём текст, и не застрять на первом незнакомом слове"),
    ("второй", "разобрать со словарём",
     "выписать незнакомое и понять конструкции"),
    ("третий", "перечитать вслух",
     "связать написание и звучание, проверить, что текст стал понятным"),
]

# как отучаться от пиньиня
PINYIN = [
    ("закрыть строку пиньиня", "листом бумаги или полоской, и это проще, чем кажется"),
    ("читать без подсказки знакомое", "начиная с тех слов, которые уже узнаёте"),
    ("возвращаться к пиньиню для проверки", "а не для чтения — это разные вещи"),
]

# ----------------------------------------------------------------- расчёты
SHARES = [c[0] for c in COVERAGE]
FREE = [c for c in COVERAGE if c[0] == 98][0]
MIN_OK = [c for c in COVERAGE if c[0] == 95][0]
TOO_HARD = [c for c in COVERAGE if c[3] == OURS][0]

# сколько незнакомых слов приходится на строку в десять слов
PER_LINE = {share: round(unknown / 10.0, 1) for share, what, unknown, st in COVERAGE}

CONFIRMED = [c for c in COVERAGE if c[3] == CONF]
OUR_OWN = [c for c in COVERAGE if c[3] == OURS]

# ----------------------------------------------------------------- проверки
assert len(COVERAGE) == 3, "ступеней три"
assert SHARES == sorted(SHARES, reverse=True), "доли идут от большей к меньшей"
assert all(0 < s < 100 for s in SHARES), "доли внутри сотни процентов"
assert all(share + unknown == 100 for share, what, unknown, st in COVERAGE), \
    "незнакомые и знакомые вместе дают сотню"

assert len(CONFIRMED) == 2 and len(OUR_OWN) == 1, "две ступени из исследований, третья наша"
assert TOO_HARD[0] == 90, "наш вывод — про девяносто процентов"
assert FREE[2] == 2 and MIN_OK[2] == 5, "на сто слов приходится два и пять незнакомых"
assert PER_LINE[98] < 1, "при свободном чтении на строку приходится меньше одного незнакомого"
assert PER_LINE[90] == 1.0, "при девяноста процентах — одно незнакомое в каждой строке"

assert len(PASSES) == 3 and [p[0] for p in PASSES] == ["первый", "второй", "третий"], \
    "проходы идут по порядку"
assert all(a and b and c for a, b, c in PASSES), "у каждого прохода есть действие и цель"
assert "не останавливаясь" in PASSES[0][1], "первый проход идёт без остановок"
assert "словар" in PASSES[1][1], "словарь появляется только на втором проходе"

assert len(PINYIN) == 3 and all(a and b for a, b in PINYIN), \
    "у каждого шага про пиньинь названо, как это делать"

import re as _re
_ALL = [x for row in COVERAGE + PASSES + PINYIN for x in row if isinstance(x, str)]
_LAT = sorted({w for s in _ALL for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT, "в данных латиница: %s" % _LAT

# ----------------------------------------------------------------- уровни
# Словник действующего стандарта, накопительно — из наших данных к разбору
# списка слов HSK по уровням. Тип текста, который при таком запасе проходит
# мерку в два незнакомых слова на сто, — НАШ ВЫВОД, а не измеренная величина.
WORDS = {1: 300, 2: 500, 3: 1000, 4: 2000, 5: 3600, 6: 5400}

# (уровень, какой текст реально проходит мерку, что с пиньинем)
LEVEL_TEXTS = [
    (1, "учебные тексты и короткие диалоги по пройденным урокам", "пиньинь есть"),
    (2, "те же учебные тексты, но длиннее, и диалоги на несколько реплик",
     "пиньинь есть"),
    (3, "учебные тексты без подсказок и первые адаптированные истории",
     "пиньиня больше нет"),
    (4, "адаптированные книги для изучающих язык", "пиньиня нет"),
    (5, "неадаптированные тексты на знакомые темы", "пиньиня нет"),
    (6, "почти любой текст, включая публицистику", "пиньиня нет"),
]

# Диалог против связного текста: чем отличается работа
DIALOG_VS = [
    ("Что держит внимание", "кто говорит и кому", "как связаны части текста"),
    ("Чего в нём больше", "частиц, обращений и коротких реплик",
     "длинных предложений и связок"),
    ("Что тренирует", "узнавание на слух и интонацию", "скорость и понимание связей"),
    ("Где пригодится на экзамене", "раздел аудирования", "раздел чтения"),
]

LEVELS_N = [l for l, t, p in LEVEL_TEXTS]
NO_PINYIN_FROM = min(l for l, t, p in LEVEL_TEXTS if "больше нет" in p or "нет" == p.split()[-1])
WORDS_TIMES = int(round(WORDS[6] / float(WORDS[1])))

assert LEVELS_N == [1, 2, 3, 4, 5, 6], "уровни идут по порядку"
assert len(LEVEL_TEXTS) == 6 and all(len(x) == 3 and all(x) for x in LEVEL_TEXTS)
assert NO_PINYIN_FROM == 3, "пиньинь исчезает с третьего уровня"
assert WORDS[6] == 5400 and WORDS_TIMES == 18,     "словник шестого уровня в восемнадцать раз больше первого"
assert len(DIALOG_VS) == 4 and all(len(x) == 3 and all(x) for x in DIALOG_VS)

_ALL2 = [x for row in LEVEL_TEXTS + DIALOG_VS for x in row if isinstance(x, str)]
_LAT2 = sorted({w for s in _ALL2 for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT2, "в данных по уровням латиница: %s" % _LAT2
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|заказать|купить|магазин",
                      " ".join(_ALL2)), "ни цен, ни магазинов в данных нет"
