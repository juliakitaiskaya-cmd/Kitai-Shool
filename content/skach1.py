# -*- coding: utf-8 -*-
"""Данные к статье «Скачать учебник HSK 1: что есть законно».

Статья отвечает не «где взять копию», а «что из материалов первого
уровня существует в электронном виде официально». Статусы у каждой
строки свои.
"""

CONF = "подтверждено"
OURS = "наш вывод"
NOCONF = "подтвердить не удалось"

# что ищут по запросу «скачать учебник HSK 1»: предмет, есть ли официально, пояснение
WANTED = [
    ("Учебник целиком", False,
     "официальной электронной версии у серии нет, и бесплатной тоже"),
    ("Рабочая тетрадь", False,
     "продаётся только на бумаге, отдельно от учебника"),
    ("Аудио к урокам", True,
     "открывается по коду из книги, у старых изданий шло диском"),
]

# что по первому уровню действительно можно получить в электронном виде
LEGAL = [
    ("Звук к урокам учебника", "по коду из купленной книги", CONF),
    ("Образцы экзаменационных заданий", "публикуются вместе с описанием экзамена", CONF),
    ("Словник первого уровня", "публикуется там же, где описание уровня", CONF),
    ("Электронные издания на русском", "бывают в продаже у книжных магазинов", NOCONF),
]

# русскоязычный учебник, существование которого проверено
RU_BOOK = "Китайский язык. Новая эра: базовый курс. Уровень HSK 1"
RU_AUTHORS = "Мин Гун и Юлия Селиверстова"

# чем копия подводит — одно упоминание, подробности у соседней статьи
COPY_RISK = "в копиях чаще всего нет звука, а задания тетради идут без ключей"

# ----------------------------------------------------------------- расчёты
NO_COUNT = sum(1 for n, yes, c in WANTED if not yes)
YES_COUNT = sum(1 for n, yes, c in WANTED if yes)
CONFIRMED = [r for r in LEGAL if r[2] == CONF]

# ----------------------------------------------------------------- проверки
assert len(WANTED) == 3 and NO_COUNT == 2 and YES_COUNT == 1, \
    "из трёх искомых вещей официально есть только одна"
assert WANTED[-1][1] is True and "код" in WANTED[-1][2], "официально доступен именно звук"
assert all(not yes for n, yes, c in WANTED[:2]), "книг в электронном виде официально нет"

assert len(LEGAL) == 4, "четыре строки того, что получить можно"
assert len(CONFIRMED) == 3, "три строки подтверждены, одна идёт с оговоркой"
assert LEGAL[-1][2] == NOCONF, "про электронные издания на русском — оговорка"
assert all(a and b for a, b, st in LEGAL), "у каждой строки названо, где это лежит"

assert "ключ" in COPY_RISK or "звук" in COPY_RISK, "у копии названа конкретная нехватка"

import re as _re
_TXT = [x for row in WANTED + LEGAL for x in row if isinstance(x, str)]
_TXT += [RU_BOOK, RU_AUTHORS, COPY_RISK]
_LAT = sorted({w for s in _TXT for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert _LAT == ["HSK"], "в данных латиница кроме HSK: %s" % _LAT
assert not _re.search(r"торрент|файлообмен|\.ru|\.com", " ".join(_TXT)), \
    "ни названий площадок, ни адресов в данных нет"
