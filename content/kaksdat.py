# -*- coding: utf-8 -*-
"""Данные к статье-навигатору «Как сдать HSK: порядок шагов».

Это хаб. Он не пересказывает ни одной соседней темы: ни устройство
уровней, ни структуру экзамена, ни день экзамена, ни сроки подготовки —
всё это разобрано отдельно и отдаётся ссылками. Своё здесь одно:
ПОРЯДОК, в котором шаги идут, и то, какие из них зависят не от вас.

Ничего нового не утверждается: все шаги — это наши же статьи, а
единственные числа считаются по самому списку шагов.
"""

YOU, CAL = "от вас", "от календаря центра"

# (номер, шаг, от кого зависит, когда делать, чем кончается)
STEPS = [
    (1, "Понять, что подтверждает сертификат", YOU, "до всего остального",
     "решением, нужен ли он вам вообще"),
    (2, "Выбрать уровень", YOU, "до всего остального",
     "целью, от которой считается план"),
    (3, "Выбрать дату сессии", CAL, "сразу после выбора уровня",
     "двумя датами в календаре: экзамена и закрытия записи"),
    (4, "Измерить стартовую точку", YOU, "до расчёта срока",
     "числом, а не ощущением «примерно третий»"),
    (5, "Посчитать срок и дневную норму", YOU, "после измерения",
     "планом, который либо сходится, либо нет"),
    (6, "Записаться до закрытия окна", CAL, "раньше, чем кажется нужным",
     "местом на сессии"),
    (7, "Заниматься по плану", YOU, "всё время между решением и экзаменом",
     "выученным объёмом"),
    (8, "Прогнать формат по времени", YOU, "в последний месяц",
     "привычкой к порядку и темпу заданий"),
    (9, "Прийти на экзамен", CAL, "в назначенный день",
     "сданной работой"),
    (10, "Получить результат", CAL, "когда объявит центр",
     "баллами и, если порог взят, сертификатом"),
]

# порядок, в котором шаги делают обычно: дату выбирают последней,
# когда «будут готовы», а измерение пропускают
USUAL = [1, 2, 7, 4, 5, 8, 3, 6, 9, 10]

# как называют экзамен в запросах и как он читается на самом деле
NAMES = [
    ("эйч-эс-кей", "по буквам, как любое латинское сокращение", True),
    ("хаэска", "попытка прочитать три буквы слитно, как одно слово", False),
    ("чискей", "смесь английского чтения букв и русского окончания", False),
    ("хэ-эс-ка", "чтение по русским названиям букв", False),
]
FULL_HAN = "汉语水平考试"
FULL_PIN = "ханьюй шуйпин каоши"
FULL_RU = "экзамен на уровень владения китайским языком"

# ----------------------------------------------------------------- расчёты
NUMS = [s[0] for s in STEPS]
BY_CAL = [s for s in STEPS if s[2] == CAL]
BY_YOU = [s for s in STEPS if s[2] == YOU]
TOTAL = len(STEPS)
CAL_N, YOU_N = len(BY_CAL), len(BY_YOU)

DATE_STEP = [s[0] for s in STEPS if "дату сессии" in s[1]][0]
DATE_USUAL = USUAL.index(DATE_STEP) + 1
DATE_SHIFT = DATE_USUAL - DATE_STEP

FIRST_CAL = min(s[0] for s in BY_CAL)
RIGHT = [n for n, why, ok in NAMES if ok]

# ----------------------------------------------------------------- проверки
assert TOTAL == 10, "шагов десять"
assert NUMS == list(range(1, 11)), "шаги пронумерованы подряд"
assert all(len(s) == 5 and all(str(x) for x in s) for s in STEPS), "у шага пять полей"
assert CAL_N == 4 and YOU_N == 6, "четыре шага зависят от календаря, шесть — от вас"
assert sorted(s[0] for s in BY_CAL) == [3, 6, 9, 10], "какие именно от календаря"
assert FIRST_CAL == 3, "первый календарный шаг — третий по счёту"

assert sorted(USUAL) == NUMS, "обычный порядок — та же десятка шагов"
assert USUAL != NUMS, "обычный порядок отличается от разумного"
assert DATE_STEP == 3 and DATE_USUAL == 7 and DATE_SHIFT == 4, \
    "выбор даты сдвинут на четыре позиции: %s вместо %s" % (DATE_USUAL, DATE_STEP)
assert USUAL.index(7) < USUAL.index(4), "обычно начинают заниматься до измерения"

assert len(NAMES) == 4 and all(len(x) == 3 for x in NAMES), "четыре варианта"
assert len(RIGHT) == 1, "одно чтение верное, три — нет"
assert RIGHT[0] == "эйч-эс-кей", "верное чтение названо"
assert len(FULL_HAN) == 6, "в полном названии шесть знаков"
assert FULL_PIN and FULL_RU, "полное название дано и в чтении, и в переводе"

import re as _re
_TXT = " ".join([str(x) for s in STEPS for x in s]
                + [x for n in NAMES for x in n if isinstance(x, str)]
                + [FULL_PIN, FULL_RU])
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|заказать|купить", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в данных нет"
