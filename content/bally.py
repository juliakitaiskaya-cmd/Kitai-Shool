# -*- coding: utf-8 -*-
"""Данные к статье «Баллы HSKK».

LEVELS — уровень, китайское название, задания (название, количество),
всего заданий, минут всего, минут подготовки, максимум баллов, порог.
"""

MAX_SCORE = 100
PASS_SCORE = 60
VALID_YEARS = 2

LEVELS = [
    ("HSKK 1", "初级",
     (("听后重复", 15), ("听后回答", 10), ("回答问题", 2)),
     17, 7),
    ("HSKK 2", "中级",
     (("听后重复", 10), ("看图说话", 2), ("回答问题", 2)),
     21, 10),
    ("HSKK 3", "高级",
     (("听后复述", 3), ("朗读", 1), ("回答问题", 2)),
     24, 10),
]

# что известно о самой оценке и что неизвестно
KNOWN = [
    ("максимум", "100 баллов на каждом уровне"),
    ("порог", "60 баллов, одинаково на всех трёх уровнях"),
    ("сумма", "считается общая, отдельного порога по частям в открытых описаниях нет"),
    ("срок действия", "два года со дня экзамена"),
]

UNKNOWN = [
    ("сколько баллов стоит каждое задание",
     "разбивка по заданиям в открытых материалах не публикуется"),
    ("точная шкала проверяющего",
     "критерии в баллах за произношение, беглость и полноту открыто не выложены"),
    ("день публикации результатов",
     "описания расходятся: называют и около месяца, и примерно 25 рабочих дней"),
]

MYTH = ("HSKK 4", "уровней у устного экзамена три, четвёртого не существует: "
                  "цифру 4 обычно переносят сюда из письменного HSK")

# ----------------------------------------------------------------- проверки
assert len(LEVELS) == 3, "уровней у HSKK ровно три"
assert len(set(l[0] for l in LEVELS)) == 3, "названия уровней не повторяются"
assert len(set(l[1] for l in LEVELS)) == 3, "китайские названия не повторяются"

for name, cn, tasks, minutes, prep in LEVELS:
    assert len(tasks) == 3, "частей на каждом уровне три: %s" % name
    assert all(n > 0 for _, n in tasks), "у каждой части задано число заданий: %s" % name
    assert prep < minutes, "подготовка короче всего экзамена: %s" % name

TOTALS = {name: sum(n for _, n in tasks) for name, cn, tasks, minutes, prep in LEVELS}
assert TOTALS["HSKK 1"] == 27 and TOTALS["HSKK 2"] == 14 and TOTALS["HSKK 3"] == 6, \
    "суммы заданий: 27, 14 и 6 — проверено по описаниям уровней"
assert TOTALS["HSKK 1"] > TOTALS["HSKK 2"] > TOTALS["HSKK 3"], \
    "чем выше уровень, тем меньше заданий и длиннее каждое"

MINUTES = [l[3] for l in LEVELS]
assert MINUTES == sorted(MINUTES), "экзамен удлиняется от уровня к уровню"

assert PASS_SCORE < MAX_SCORE and MAX_SCORE == 100
assert len(UNKNOWN) >= 3, "о неизвестном говорим не одной строкой"
assert MYTH[0] == "HSKK 4" and "не существует" in MYTH[1]

COMMON = set.intersection(*[set(t[0] for t in l[2]) for l in LEVELS])
assert COMMON == {"回答问题"}, "через все три уровня проходит только 回答问题"
