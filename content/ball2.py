# -*- coding: utf-8 -*-
"""Данные к статье «Результаты HSK: что значит ваш балл».

Ось узкая и взята из одного ключа брифа: человек видит два результата
за один и тот же экзамен — 195 и 260 — и не понимает, в чём между ними
разница, если сертификат одинаковый.

Чего здесь намеренно нет: подсчёта баллов и прикидки по пробнику. Это
разобрано в опубликованной статье про систему оценки и в нашей готовой
статье про то, как считается результат. Здесь другое — что сумма
скрывает и чего не скрывает, посчитанное прямо.

Все числа ниже считаются в коде из двух величин: разделов три,
в каждом сто баллов.
"""

SECTIONS = 3          # аудирование, чтение, письмо
PER = 100             # баллов за раздел
TOP = SECTIONS * PER  # 300
THRESHOLD = 180       # порог сдачи на уровнях с тремя разделами

# два результата из вопроса, вокруг которых строится статья
LOW, HIGH = 195, 260


def profiles(total, sections=SECTIONS, per=PER):
    """Сколько раскладов по разделам даёт одну и ту же сумму.

    Считаются целые баллы от нуля до ста в каждом разделе.
    """
    if sections == 1:
        return 1 if 0 <= total <= per else 0
    return sum(profiles(total - x, sections - 1, per) for x in range(per + 1))


def floor_of(total, sections=SECTIONS, per=PER):
    """Самый низкий балл, который ещё возможен в разделе при такой сумме."""
    return max(0, total - (sections - 1) * per)


# ряд для таблицы и для картинок
ROW_SUMS = [THRESHOLD, LOW, 200, 220, 240, HIGH, 280, TOP]
TABLE = [(s, profiles(s), floor_of(s)) for s in ROW_SUMS]

P_LOW = profiles(LOW)          # 5626
P_HIGH = profiles(HIGH)        # 861
TIMES = round(P_LOW / float(P_HIGH), 1)   # во сколько раз больше раскладов

FLOOR_LOW = floor_of(LOW)      # 0
FLOOR_HIGH = floor_of(HIGH)    # 60

# сумма, начиная с которой провал в разделе уже невозможен
GUARD = (SECTIONS - 1) * PER + 1   # 201

SPREAD = TOP - THRESHOLD           # 120
SHARE = int(round(100.0 * THRESHOLD / TOP))   # 60

# что одна и та же сумма говорит и чего не говорит
SAYS = [
    ("Сдан ли уровень", "да", "сумма сравнивается с порогом, и этого хватает"),
    ("Есть ли провал в разделе", "только выше двухсот",
     "ниже этой суммы ноль в разделе арифметически возможен"),
    ("Где именно слабое место", "нет",
     "это видно по разделам в отчёте, а не по сумме"),
    ("Готовы ли вы к следующему уровню", "нет",
     "следующая ступень опирается на предыдущую целиком"),
]

# ----------------------------------------------------------------- проверки
assert TOP == 300 and THRESHOLD == 180, "три раздела по сто, порог сто восемьдесят"
assert SHARE == 60, "порог — три пятых от максимума"
assert SPREAD == 120, "от порога до максимума сто двадцать баллов"
assert THRESHOLD < LOW < HIGH < TOP, "оба результата внутри сданного уровня"

assert profiles(TOP) == 1, "полный балл собирается единственным способом"
assert profiles(0) == 1, "нулевая сумма тоже единственна"
assert P_LOW == 5626 and P_HIGH == 861, "раскладов: %d и %d" % (P_LOW, P_HIGH)
assert TIMES == 6.5, "за низким результатом раскладов в шесть с половиной раз больше"

assert FLOOR_LOW == 0, "при ста девяноста пяти раздел может быть нулевым"
assert FLOOR_HIGH == 60, "при двухстах шестидесяти ни один раздел не ниже шестидесяти"
assert floor_of(GUARD) == 1 and floor_of(GUARD - 1) == 0, \
    "граница гарантии проходит по двумстам одному: %d" % GUARD

assert [t[0] for t in TABLE] == sorted(t[0] for t in TABLE), "суммы по возрастанию"
assert [t[1] for t in TABLE] == sorted((t[1] for t in TABLE), reverse=True), \
    "чем выше сумма, тем меньше раскладов"
assert all(a[2] <= b[2] for a, b in zip(TABLE, TABLE[1:])), "пол не убывает"
assert len(SAYS) == 4 and all(len(s) == 3 and all(s) for s in SAYS)

import re as _re
_TXT = " ".join(x for s in SAYS for x in s)
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
assert not _re.search(r"[A-Za-z]{2,}", _TXT), "латиницы в этих данных нет"
assert not _re.search(r"резюме|intermediate", _TXT), \
    "резюме и словесные ступени разобраны у соседа и сюда не переносятся"
