# -*- coding: utf-8 -*-
"""Данные к статье «Слова HSK 4».

Числа действующего стандарта сверены по сводным таблицам в нескольких
независимых источниках. Там, где источники считают по-разному, это
названо прямо, а своё число не подставляется.
"""

CONF = "сошлось в нескольких источниках"
DESCR = "по описаниям публикаций словника"
SPLIT = "источники считают по-разному"

LEVEL = 4

WORDS_NEW = 1000          # прибавка уровня по действующему стандарту
WORDS_TOTAL = 2000        # накопительно к концу уровня
OLD_TOTAL = 1200          # прежний стандарт, накопительно
OLD_NEW = 600             # прежний стандарт, прибавка уровня

READ_NEW, READ_TOTAL = 441, 1096      # знаки для узнавания
WRITE_NEW, WRITE_TOTAL = 150, 400     # знаки для письма от руки
GRAM_NEW = 95                          # новых грамматических пунктов

# ---------------------------------------------- четыре счёта одного уровня
# (что за список, сколько в нём позиций, как понять, по чему он собран)
COUNTS = [
    ("Весь словарь уровня", str(WORDS_TOTAL),
     "накопительная цифра: вместе с первыми тремя уровнями", CONF),
    ("Только прибавка уровня", str(WORDS_NEW),
     "новые слова четвёртого уровня, без младших", CONF),
    ("Прежний стандарт", str(OLD_TOTAL),
     "накопительная цифра старой шкалы, список собран до пересмотра", CONF),
    ("Список по урокам учебника", "зависит от книги",
     "привязан к тому, а не к уровню: в нём лексика конкретных уроков", CONF),
]

# почему даже «правильные» списки расходятся на пару десятков позиций
ENTRY_NOTE = ("в словнике считаются записи, а не уникальные слова: слово с двумя "
              "чтениями занимает две строки")
ENTRY_STATUS = DESCR

# ---------------------------------------------- чего в списках не бывает
NO_IN_LIST = [
    ("Примеров употребления", "словник даёт слово и чтение, фразы в нём не предусмотрены"),
    ("Разметки по темам", "порядок в словнике алфавитный"),
    ("Указания, какое значение спросят", "у многозначного слова в списке одна строка"),
]

# ---------------------------------------------- расчёты
DIFF_OLD = WORDS_TOTAL - OLD_TOTAL        # 800 — разница со старой шкалой
HALF = WORDS_NEW * 100 // WORDS_TOTAL     # 50 % — доля прибавки в накопительной цифре
PER_100 = int(round(100.0 * READ_NEW / WORDS_NEW))   # 44 новых знака на сто новых слов
OLD_GROWTH = round(WORDS_NEW / float(OLD_NEW), 1)    # во сколько раз выросла прибавка

# ---------------------------------------------- проверки
assert WORDS_TOTAL == 2000 and WORDS_NEW == 1000, "числа уровня взяты из сверки"
assert HALF == 50, "прибавка уровня — ровно половина накопительной цифры"
assert DIFF_OLD == 800, "разница с прежней шкалой посчитана"
assert OLD_GROWTH > 1, "прибавка выросла против прежнего стандарта"
assert READ_NEW < WORDS_NEW and PER_100 == 44, \
    "новых знаков меньше, чем новых слов, и доля посчитана"
assert WRITE_NEW < READ_NEW, "писать требуют меньше, чем узнавать"

assert len(COUNTS) == 4, "четыре счёта одного уровня"
assert [c[1] for c in COUNTS][:3] == ["2000", "1000", "1200"], "три числа и один переменный"
assert COUNTS[3][1] == "зависит от книги", "у списка по урокам числа нет"
assert len(set(c[1] for c in COUNTS)) == 4, "все четыре варианта различны"
assert ENTRY_STATUS == DESCR, "про записи словника стоит оговорка"

assert len(NO_IN_LIST) == 3 and all(a and b for a, b in NO_IN_LIST)

import re as _re
_TXT = " ".join([n + " " + v + " " + w for n, v, w, s in COUNTS]
                + [a + " " + b for a, b in NO_IN_LIST] + [ENTRY_NOTE])
assert not _re.search(r"\bруб|\bцена|\bюан", _TXT), "цен в данных нет"
assert not _re.search(r"\.ru|\.com|\.cn|торрент", _TXT), "адресов и площадок в данных нет"
assert not _re.search(r"добор|добира|добрат", _TXT), "жаргона в данных нет"
