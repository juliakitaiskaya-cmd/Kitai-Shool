# -*- coding: utf-8 -*-
"""Данные к статье «Какой уровень HSK нужен для поступления».

Требования устанавливает вуз, поэтому ни одна строка не подаётся как
универсальная норма: у каждой стоит статус и оговорка о том, что
планку определяет программа.
"""

CONF = "подтверждено"
DESC = "по описаниям"

# куда, какой уровень обычно просят, оговорка, статус
TRACKS = [
    ("Языковой год", "обычно не требуется",
     "экзамен сдают во время самого года, а не до него", DESC),
    ("Бакалавриат на китайском", "HSK 4 как минимум",
     "сильные вузы и часть направлений просят HSK 5", DESC),
    ("Бакалавриат на английском", "китайский может не требоваться",
     "вместо него спрашивают экзамен по английскому", DESC),
    ("Магистратура на китайском", "HSK 4 или 5",
     "планка зависит от вуза и направления", DESC),
    ("Стипендиальные программы", "зависит от программы",
     "иногда добавляют результат устной части", DESC),
]

# что означает один и тот же номер уровня в двух шкалах: слов накопительно
SCALE = [
    (3, 600, 1000),
    (4, 1200, 2000),
    (5, 2500, 3600),
    (6, 5000, 5400),
]

# что проверить на странице программы
CHECKS = [
    ("номер уровня", "он может быть записан по прежней шкале"),
    ("порог баллов", "уровень сдан — ещё не значит, что балл достаточный"),
    ("срок, за который принимают результат", "у программ он свой"),
    ("нужна ли устная часть", "её спрашивают не всегда и не везде"),
]

# ----------------------------------------------------------------- расчёты
GAPS = {lvl: new - old for lvl, old, new in SCALE}
RATIO = {lvl: round(float(new) / old, 2) for lvl, old, new in SCALE}
BIGGEST_ABS = max(GAPS, key=lambda k: GAPS[k])          # где разрыв больше в словах
TOP_RATIO = max(RATIO.values())                          # где он больше по доле
BIGGEST_REL = sorted(l for l in RATIO if RATIO[l] == TOP_RATIO)

CONFIRMED = [t for t in TRACKS if t[3] == CONF]
UNCONFIRMED = [t for t in TRACKS if t[3] == DESC]

# ----------------------------------------------------------------- проверки
assert len(TRACKS) == 5, "направлений пять"
assert len(set(t[0] for t in TRACKS)) == 5, "названия не повторяются"
assert all(t[1] and t[2] for t in TRACKS), "у каждого направления есть требование и оговорка"
assert all(t[3] == DESC for t in TRACKS), \
    "ни одно требование не подтверждено официально: планку ставит вуз"
assert not CONFIRMED, "подтверждённых требований нет и быть не может"

assert len(SCALE) == 4 and [l for l, o, n in SCALE] == [3, 4, 5, 6], "сравниваем уровни 3–6"
assert all(new > old for lvl, old, new in SCALE), "в новой шкале словарь больше на всех"
assert GAPS[4] == 800, "на четвёртом уровне разница ровно восемьсот слов"
assert BIGGEST_ABS == 5 and GAPS[5] == 1100, \
    "в словах сильнее всего разошёлся пятый уровень"
assert BIGGEST_REL == [3, 4] and TOP_RATIO == 1.67, \
    "по доле разрыв наибольший на третьем и четвёртом, и он одинаков"
assert RATIO[6] < 1.1 and min(RATIO.values()) == RATIO[6], \
    "на шестом уровне шкалы почти сошлись"

assert len(CHECKS) == 4 and all(a and b for a, b in CHECKS), \
    "у каждой проверки названо, зачем она"
assert any("порог" in a for a, b in CHECKS), "про порог баллов спросить обязательно"
