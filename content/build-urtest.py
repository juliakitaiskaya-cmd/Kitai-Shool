def pct(v):
    if v >= 0.01:
        return ("%.2f" % (v * 100)).replace(".", ",") + "&nbsp;%"
    if v >= 0.000001:
        return ("%.4f" % (v * 100)).replace(".", ",") + "&nbsp;%"
    return "меньше одной миллионной доли"


