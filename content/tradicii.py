# -*- coding: utf-8 -*-
"""Данные к статье «Традиции китайцев». Один файл на статью и на обе картинки.

GENS — ряды поколений для обложки: кем приходится, знак поколения, подпись.
FAMILY — состав семьи по периодам: год, подпись, прародителей, родителей, детей.
"""

GENS = [
    ("старшее поколение", "дед и бабушка", "福", "fú", "благополучие"),
    ("среднее поколение", "отец и мать", "德", "dé", "достоинство"),
    ("младшее поколение", "дети", "文", "wén", "учёность"),
]

FAMILY = [
    (1979, "до ограничений", 4, 2, 4, "детей в семье обычно несколько"),
    (2016, "при одном ребёнке", 4, 2, 1, "схема 4-2-1: шестеро взрослых на одного"),
    (2021, "после разрешения трёх", 4, 2, 3, "разрешено до трёх, но решают семьи"),
]

YEARS = {"начало ограничений": 1979, "двое детей для всех": 2016, "трое детей": 2021,
         "закон о пожилых": 2013}

# ----------------------------------------------------------------- проверки
assert len(GENS) == 3, "рядов поколений ровно три"
assert len(set(g[2] for g in GENS)) == 3, "знаки поколений не должны повторяться"
assert all(len(g[2]) == 1 for g in GENS), "знак поколения — один иероглиф"

assert [f[0] for f in FAMILY] == sorted(f[0] for f in FAMILY), "периоды идут по возрастанию года"
assert len(set(f[0] for f in FAMILY)) == 3, "периодов три"

ONE = [f for f in FAMILY if f[1] == "при одном ребёнке"][0]
assert (ONE[2], ONE[3], ONE[4]) == (4, 2, 1), "схема должна давать именно 4-2-1"
assert ONE[2] + ONE[3] == 6, "на одного ребёнка приходится шестеро взрослых"

assert FAMILY[0][4] > FAMILY[1][4] and FAMILY[2][4] > FAMILY[1][4], \
    "число детей должно падать к периоду одного ребёнка и расти после"

assert YEARS["двое детей для всех"] > YEARS["закон о пожилых"] > YEARS["начало ограничений"], \
    "годы в тексте и на картинках должны совпадать по порядку"
assert set(YEARS.values()) >= set(f[0] for f in FAMILY) - {2016}, "годы периодов названы в тексте"

BAN = ("Ван", "Ли", "Чжан", "Чэнь", "Лю")
assert not any(b in str(GENS) or b in str(FAMILY) for b in BAN), \
    "имён и фамилий в данных нет — придумывать их мы не станем"
