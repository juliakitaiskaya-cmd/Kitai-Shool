def table(caption, rows, start):
    out = ['<div class="table-wrap">', '<table>',
           '  <caption>%s</caption>' % caption,
           '  <thead><tr><th>№</th><th>Фраза</th><th>Пиньинь</th><th>Перевод</th><th>Когда говорят</th></tr></thead>',
           '  <tbody>']
    for i, (h, p, r, w) in enumerate(rows, start):
        out.append('    <tr><td>%d</td><td><b class="han">%s</b></td><td>%s</td><td>%s</td><td>%s</td></tr>'
                   % (i, h, p, r, w))
    out += ['  </tbody>', '</table>', '</div>']
    return "\n".join(out)

