# -*- coding: utf-8 -*-
"""Данные к статье «Международные экзамены по китайскому языку».

Страница-сравнение: чем экзамены отличаются друг от друга. Устройство
каждого разобрано у нас отдельно и сюда не переносится — здесь только
то, чего нет ни в одной из тех статей: сопоставление между собой.

Всё, что утверждается, взято из наших же разборов. Про тайваньский
экзамен подробностей у нас нет, и это сказано прямо, а не замолчано.
"""

AUD, READ, WRITE, SPEAK = "аудирование", "чтение", "письмо", "речь"
SKILLS = [AUD, READ, WRITE, SPEAK]

# (экзамен, для кого, уровней, какие навыки проверяет, форма)
EXAMS = [
    ("HSK", "для всех, кто учит китайский", 6, [AUD, READ, WRITE], "письменный"),
    ("HSKK", "для тех, кому нужна подтверждённая речь", 3, [SPEAK], "устный"),
    ("YCT", "для школьников", 4, [AUD, READ], "письменный"),
]

# экзамен, о котором у нас нет разбора: называем и честно отказываемся
NO_DATA = ("TOCFL", "тайваньский экзамен, ориентированный на традиционные знаки")

# чем экзамены различаются — четыре основания, по которым их и выбирают
AXES = [
    ("Кому предъявлять результат",
     "вуз, работодатель или школа — у каждого свой список"),
    ("Возраст",
     "для школьников есть отдельный экзамен со своим форматом"),
    ("Какой навык нужно подтвердить",
     "письменный и устный — это два разных экзамена"),
    ("Какая письменность",
     "упрощённые знаки или традиционные"),
]

# ответ на вопрос «все ли сдают экзамен после курсов»
VOLUNTARY = [
    ("Нужен документ", "вуз, работа, виза, стипендия", "экзамен сдают"),
    ("Нужна внешняя проверка", "понять, где вы на самом деле", "экзамен полезен"),
    ("Не нужно ни то, ни другое", "учу для себя", "можно не сдавать"),
]

# ----------------------------------------------------------------- расчёты
NAMES = [e[0] for e in EXAMS]
LEVELS = {e[0]: e[2] for e in EXAMS}
COVER = {e[0]: e[3] for e in EXAMS}

HSK_N = len(COVER["HSK"])
SPEAK_N = len(COVER["HSKK"])
TOGETHER = sorted(set(COVER["HSK"]) | set(COVER["HSKK"]), key=SKILLS.index)
ALONE = [e for e in NAMES if len(COVER[e]) == len(SKILLS)]

LEVELS_SET = sorted({v for v in LEVELS.values()})
WRITTEN = [e[0] for e in EXAMS if e[4] == "письменный"]
ORAL = [e[0] for e in EXAMS if e[4] == "устный"]

# ----------------------------------------------------------------- проверки
assert NAMES == ["HSK", "HSKK", "YCT"], "три экзамена, которые мы разбирали"
assert len(SKILLS) == 4 and len(set(SKILLS)) == 4, "навыков четыре"
assert HSK_N == 3 and SPEAK_N == 1, "письменный закрывает три навыка, устный — один"
assert TOGETHER == SKILLS, "вместе они дают все четыре"
assert not ALONE, "ни один экзамен не покрывает все четыре навыка в одиночку"
assert SPEAK not in COVER["HSK"], "речь письменным экзаменом не проверяется"
assert WRITE not in COVER["YCT"], "в детском экзамене письма от руки нет"

assert LEVELS == {"HSK": 6, "HSKK": 3, "YCT": 4}, "у каждого своё число уровней"
assert LEVELS_SET == [3, 4, 6], "три разные шкалы, а не одна"
assert len(WRITTEN) == 2 and len(ORAL) == 1, "два письменных и один устный"

assert NO_DATA[0] == "TOCFL" and NO_DATA[1], "экзамен без разбора назван"
assert len(AXES) == 4 and all(len(a) == 2 and all(a) for a in AXES), "четыре основания"
assert len(VOLUNTARY) == 3 and all(len(v) == 3 and all(v) for v in VOLUNTARY)
assert VOLUNTARY[-1][2] == "можно не сдавать", "ответ про необязательность есть"

import re as _re
_TXT = " ".join([str(x) for e in EXAMS for x in e if isinstance(x, str)]
                + [x for a in AXES for x in a]
                + [x for v in VOLUNTARY for x in v] + list(NO_DATA))
assert not _re.search(r"\bруб(?:л|\.)|\bюан|₽|¥|заказать|купить", _TXT), "сумм нет"
assert not _re.search(r"\.ru|\.com|\.cn|www\.|http", _TXT), "адресов нет"
assert not _re.search(r"добор|добира|добрат|добер", _TXT), "без жаргона"
