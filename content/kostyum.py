# -*- coding: utf-8 -*-
"""Данные к статье «Традиционный костюм в Китае».

ERAS — эпохи: название, годы от и до, фасон знаками, пиньинь, перевод,
линия пояса (доля высоты фигуры сверху вниз; None — талия не обозначена),
примета эпохи.
RANKS — подтверждённые позиции знаков ранга 补子.
"""

ERAS = [
    ("Чжоу и Хань", -1046, 220, "深衣", "shēnyī", "цельный халат",
     0.50, "верх и низ скроены отдельно, но сшиты вместе"),
    ("Тан", 618, 907, "齐胸襦裙", "qíxiōng rúqún", "юбка под грудью",
     0.34, "юбку подвязывают высоко, рукава широкие"),
    ("Сун", 960, 1279, "褙子", "bèizǐ", "распашная накидка",
     0.50, "силуэт прямой, без подчёркнутой фигуры"),
    ("Мин", 1368, 1644, "袄裙", "ǎoqún", "кофта поверх юбки",
     0.44, "с этой эпохой связана юбка 马面裙"),
    ("Цин", 1644, 1912, "旗装", "qízhuāng", "халат знамённых",
     None, "прямой крой, линия талии не обозначена"),
]

RANKS = [
    ("гражданские", 1, "仙鹤", "журавль"),
    ("гражданские", 3, "孔雀", "павлин"),
    ("гражданские", 5, "白鹇", "серебряный фазан"),
    ("гражданские", 6, "鹭鸶", "цапля"),
    ("военные", 1, "麒麟", "цилинь"),
    ("военные", 2, "狮子", "лев"),
    ("военные", 3, "豹", "леопард"),
    ("военные", 4, "虎", "тигр"),
]

TANGZHUANG_YEAR = 2001          # саммит АТЭС в Шанхае, после которого закрепилось имя 唐装

# ----------------------------------------------------------------- проверки
assert len(ERAS) == 5, "эпох в разборе пять"
starts = [e[1] for e in ERAS]
assert starts == sorted(starts), "эпохи идут по возрастанию"
for (n1, s1, e1, *_), (n2, s2, e2, *_) in zip(ERAS, ERAS[1:]):
    assert e1 <= s2, "годы эпох не должны пересекаться: %s и %s" % (n1, n2)

assert len(set(e[3] for e in ERAS)) == 5, "названия фасонов не должны повторяться"

belts = {e[0]: e[6] for e in ERAS}
assert belts["Тан"] < belts["Чжоу и Хань"], "при Тан пояс выше, чем при Хань"
assert belts["Мин"] < belts["Сун"], "при Мин пояс выше, чем при Сун"
assert belts["Цин"] is None, "у Цин линия талии не задана"
assert all(0 < b < 1 for b in belts.values() if b is not None), "доля пояса внутри фигуры"

CIVIL = [r for r in RANKS if r[0] == "гражданские"]
MIL = [r for r in RANKS if r[0] == "военные"]
assert len(CIVIL) == 4 and len(MIL) == 4, "подтверждённых позиций по четыре в каждой группе"
assert len(RANKS) == 8, "всего подтверждённых позиций восемь — полной таблицы девяти рангов нет"
assert all(1 <= r[1] <= 9 for r in RANKS), "ранги с первого по девятый"
assert len(set((r[0], r[1]) for r in RANKS)) == len(RANKS), "позиции не повторяются"
