# -*- coding: utf-8 -*-
"""Данные к статье «Указательные местоимения в китайском».

PAIRS — парные формы: 这-форма, её пиньинь, 那-форма, её пиньинь, значение, пометка.
PHRASE — блоки фразы 这两本书 по порядку сборки.
SCALE — шкала дальности для обложки.
"""

PAIRS = [
    ("这", "zhè", "那", "nà", "этот и тот", "перед счётным словом"),
    ("这个", "zhège", "那个", "nàge", "этот и тот предмет", "самая частая форма"),
    ("这些", "zhèxiē", "那些", "nàxiē", "эти и те", "счётное слово уже не нужно"),
    ("这里", "zhèlǐ", "那里", "nàlǐ", "здесь и там", "нейтрально"),
    ("这儿", "zhèr", "那儿", "nàr", "здесь и там", "разговорнее, чаще на севере"),
    ("这边", "zhèbiān", "那边", "nàbiān", "эта и та сторона", "мягче, чем 这里"),
    ("这位", "zhèwèi", "那位", "nàwèi", "этот и тот человек", "вежливо, со счётным словом 位"),
    ("这么", "zhème", "那么", "nàme", "так, настолько", "отвечает на «насколько»"),
    ("这样", "zhèyàng", "那样", "nàyàng", "такой, таким образом", "отвечает на «как»"),
    ("这时", "zhèshí", "那时", "nàshí", "в это и в то время", "о времени"),
]

PHRASE = [
    ("这", "zhè", "указательное"),
    ("两", "liǎng", "число"),
    ("本", "běn", "счётное слово"),
    ("书", "shū", "существительное"),
]
BROKEN = ["这", "两", "书"]        # то же без счётного слова — так сказать нельзя

SCALE = [
    ("в руке", "这个", "zhège"),
    ("на столе", "这本书", "zhè běn shū"),
    ("в другом конце комнаты", "那个", "nàge"),
    ("на улице", "那边", "nàbiān"),
]

# ----------------------------------------------------------------- проверки
assert len(PAIRS) == 10, "парных форм десять"
for near, npy, far, fpy, mean, note in PAIRS:
    assert near.startswith("这"), "ближняя форма начинается с 这: %s" % near
    assert far.startswith("那"), "дальняя форма начинается с 那: %s" % far
    assert len(near) == len(far), "формы в паре одной длины: %s и %s" % (near, far)

pys = [p[1] for p in PAIRS] + [p[3] for p in PAIRS]
assert len(set(pys)) == len(pys), "чтения не должны повторяться"

for row in PAIRS:
    assert not any(x.startswith("哪") for x in (row[0], row[2])), \
        "哪-формы разобраны у другой статьи — в данные не берём"

assert len(PHRASE) == 4, "в конструкторе четыре блока"
assert [b[0] for b in PHRASE] == ["这", "两", "本", "书"], \
    "порядок: указательное, число, счётное слово, существительное"
assert [b[2] for b in PHRASE] == ["указательное", "число", "счётное слово", "существительное"], \
    "подписи блоков совпадают с порядком"

full = [b[0] for b in PHRASE]
assert len(full) - len(BROKEN) == 1, "нерабочий вариант короче ровно на один блок"
missing = [x for x in full if x not in BROKEN]
assert missing == ["本"], "в нерабочем варианте не хватает именно счётного слова"

assert len(SCALE) == 4, "на шкале четыре отметки"
assert [s[1][0] for s in SCALE] == ["这", "这", "那", "那"], \
    "ближние отметки идут первыми, дальние — последними"
