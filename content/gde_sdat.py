# -*- coding: utf-8 -*-
"""Данные к статье «Где сдать HSK: что значит сдать онлайн».

Под словом «онлайн» люди имеют в виду три разные вещи, и только две
из них — экзамен. У каждого пункта стоит статус источника.
"""

CONF = "подтверждено"
DESC = "по описаниям"

# название, где проходит, что это даёт, статус
WAYS = [
    ("Компьютерный формат", "в центре тестирования",
     "настоящий экзамен и официальный сертификат", CONF),
    ("Домашний формат с наблюдением", "дома, под камерой",
     "настоящий экзамен, но доступен не везде и не на всех уровнях", DESC),
    ("Онлайн-тренажёр", "где угодно",
     "тренировка без всякого статуса: сертификата не даёт", CONF),
]

# что делать, если центра в городе нет
NO_CENTER = [
    ("съездить в ближайший город", "экзамен идёт в один день по всей стране, "
     "и дата известна заранее"),
    ("выбрать центр с компьютерным форматом", "он бывает там, где бумажный не проводят"),
    ("спросить про домашний формат", "его дают не все центры, и уточнять нужно до записи"),
]

# чего нельзя сделать, как бы ни хотелось
IMPOSSIBLE = [
    ("сдать экзамен самому себе дома без наблюдения", "результат не будет засчитан"),
    ("получить сертификат за онлайн-тренажёр", "он не связан с экзаменом"),
    ("записаться после закрытия регистрации", "сроки у каждого центра свои"),
]

# ----------------------------------------------------------------- расчёты
REAL = [w for w in WAYS if "настоящий экзамен" in w[2]]
NOT_REAL = [w for w in WAYS if "настоящий экзамен" not in w[2]]
CONFIRMED = [w for w in WAYS if w[3] == CONF]
UNCONFIRMED = [w for w in WAYS if w[3] == DESC]

# ----------------------------------------------------------------- проверки
assert len(WAYS) == 3, "способов три"
assert len(set(w[0] for w in WAYS)) == 3, "названия не повторяются"
assert all(w[1] and w[2] for w in WAYS), "у каждого способа названы место и результат"
assert all(w[3] in (CONF, DESC) for w in WAYS), "у каждого способа есть статус"

assert len(REAL) == 2 and len(NOT_REAL) == 1, "экзаменом являются два способа из трёх"
assert NOT_REAL[0][0] == "Онлайн-тренажёр", "не экзамен — именно тренажёр"
assert "сертификата не даёт" in NOT_REAL[0][2], "про тренажёр сказано прямо"

assert len(CONFIRMED) == 2 and len(UNCONFIRMED) == 1, "один способ идёт с оговоркой"
assert UNCONFIRMED[0][0].startswith("Домашний"), "с оговоркой — именно домашний формат"

assert len(NO_CENTER) == 3 and all(a and b for a, b in NO_CENTER), \
    "у каждого варианта названо, почему он работает"
assert len(IMPOSSIBLE) == 3 and all(a and b for a, b in IMPOSSIBLE), \
    "у каждого запрета названа причина"
assert all("сертификат" not in a for a, b in NO_CENTER), \
    "варианты описывают действие, а не обещание сертификата"

# --------------------------------------------------------------- география
# Города, чьи центры объявили сессии на осень 2026 года. Источник — наша же
# сверка расписания от 8 сентября 2026. Названий площадок и адресов нет
# намеренно: список адресов портится за сезон.
CHECKED = "8 сентября 2026 года"
CITIES = ["Москва", "Петербург", "Новосибирск", "Красноярск", "Улан-Удэ",
          "Владивосток", "Благовещенск", "Сочи", "Ростов-на-Дону"]
# города, где центры есть, а даты на осень не были объявлены к сверке
CITIES_SOON = ["Екатеринбург", "Иркутск", "Уфа"]
MULTI = ["Москва", "Петербург"]        # города, где в сверке больше одного центра
MULTI_IN = ["Москве", "Петербурге"]    # предложный падеж для текста

# --------------------------------------------------------------- версия экзамена
SWITCH = "13 декабря 2026 года"        # с этой даты уровни сдают по новому стандарту
LAST_OLD = "7 ноября 2026 года"        # последняя обычная сессия уровней 1—6
TODAY = "17 ноября 2026 года"
# сессии осени раньше даты перехода, по которым версия не подтверждена
BEFORE_SWITCH = ["7 декабря", "8 декабря"]

# --------------------------------------------------------------- расчёты
CITIES_ALL = CITIES + CITIES_SOON
assert len(CITIES) == 9, "в сверке девять городов с объявленными датами"
assert len(CITIES_SOON) == 3, "ещё три города без объявленных дат"
assert len(set(CITIES_ALL)) == len(CITIES_ALL), "города не повторяются"
assert all(c not in CITIES_SOON for c in CITIES), "списки не пересекаются"
assert all(c in CITIES for c in MULTI), "города с несколькими центрами есть в основном списке"
assert len(MULTI_IN) == len(MULTI), "у каждого такого города задан предложный падеж"
assert all(a[:3] == b[:3] for a, b in zip(MULTI, MULTI_IN)), \
    "падежная форма относится к тому же городу"
assert "Москва" in CITIES, "Москва в списке: про неё три ключа"
assert "Оренбург" not in CITIES_ALL, \
    "Оренбурга в нашей сверке нет, и выдумывать его нельзя"
assert len(BEFORE_SWITCH) == 2, "двух сессий осени нет подтверждения по версии"

import re as _re
_LAT = sorted({w for s in CITIES_ALL + BEFORE_SWITCH + [CHECKED, SWITCH, LAST_OLD, TODAY]
               for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT, "в данных латиница: %s" % _LAT

# --------------------------------------------------------------- часовые пояса
# Города из сверки, разложенные по сдвигу от московского времени.
# Сдвиги — обычная география, города — только из списков выше.
ZONES = [
    ("Московское время", ["Петербург", "Москва", "Сочи", "Ростов-на-Дону"]),
    ("+2 часа", ["Уфа", "Екатеринбург"]),
    ("+4 часа", ["Новосибирск", "Красноярск"]),
    ("+5 часов", ["Иркутск", "Улан-Удэ"]),
    ("+6 часов", ["Благовещенск"]),
    ("+7 часов", ["Владивосток"]),
]

_Z = [c for z, cs in ZONES for c in cs]
assert sorted(_Z) == sorted(CITIES_ALL), \
    "в поясах те же города, что в сверке: %s" % sorted(set(_Z) ^ set(CITIES_ALL))
assert len(_Z) == len(set(_Z)) == 12, "каждый город стоит в одном поясе"
assert ZONES[0][1][0] == "Петербург" and ZONES[-1][1][-1] == "Владивосток", \
    "лестница идёт с запада на восток"
assert all(cs for z, cs in ZONES), "пустых поясов нет"
