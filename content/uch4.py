# -*- coding: utf-8 -*-
"""Данные к статье «Учебник HSK 4».

Числа по томам взяты с нашей же страницы про серию. None означает, что
цифру подтвердить не удалось. Оценка по тому 4B считается и помечается
как расчёт, а не выдаётся за факт.
"""

CONF = "подтверждено"
OURS = "наш расчёт"

VOL_A = ("4A", 10, 300)        # метка, уроков, слов — числа сошлись в описаниях
VOL_B = ("4B", None, None)     # по второму тому чисел нет

# накопительные словники
LEVEL_NEW, LEVEL_OLD = 2000, 1200     # к концу четвёртого уровня
PREV_NEW, PREV_OLD = 1000, 600        # к концу третьего

# комплект уровня
BOOKS_IN_VOLUME = 3            # учебник, тетрадь, книга для преподавателя
VOLUMES_ON_LEVEL = 2           # 4A и 4B
BOOKS_STUDENT = 4              # два учебника и две тетради

# экзамен четвёртого уровня по действующей редакции
EXAM = {"вопросов": 100, "минут": 105, "письмо_заданий": 15, "письмо_минут": 25,
        "максимум": 300, "порог": 180}

# ----------------------------------------------------------------- расчёты
STEP_NEW = LEVEL_NEW - PREV_NEW        # прибавка на уровне по действующей шкале
STEP_OLD = LEVEL_OLD - PREV_OLD        # по прежней
A_WORDS = VOL_A[2]
B_EST = STEP_OLD - A_WORDS             # оценка словаря второго тома
A_SHARE = int(round(100.0 * A_WORDS / STEP_NEW))        # доля одного тома в прибавке
BOTH_SHARE = int(round(100.0 * STEP_OLD / STEP_NEW))    # доля обоих томов
REST = STEP_NEW - STEP_OLD             # сколько добирать сверх двух книг
COVER_LEVEL = int(round(100.0 * LEVEL_OLD / LEVEL_NEW))

# ----------------------------------------------------------------- проверки
assert VOL_A == ("4A", 10, 300), "числа тома 4A совпадают с нашей страницей про серию"
assert VOL_B[1] is None and VOL_B[2] is None, "по тому 4B чисел нет и подставлять нечего"
assert STEP_NEW == 1000 and STEP_OLD == 600, "прибавки на уровне считаются из шкал"
assert STEP_NEW == PREV_NEW, \
    "на четвёртом уровне добавляется столько же, сколько накоплено за первые три"
assert B_EST == 300 and A_WORDS + B_EST == STEP_OLD, "оценка второго тома считается"
assert A_SHARE == 30 and BOTH_SHARE == 60, "один том — меньше трети прибавки, оба — три пятых"
assert A_SHARE < 34, "один том не дотягивает до трети"
assert REST == 400 and STEP_OLD + REST == STEP_NEW, "добор сверх двух книг"
assert COVER_LEVEL == 60, "по накопительной шкале серия закрывает три пятых уровня"

assert VOLUMES_ON_LEVEL == 2 and BOOKS_IN_VOLUME == 3
assert BOOKS_STUDENT == VOLUMES_ON_LEVEL * 2, "ученику нужны учебник и тетрадь каждого тома"
assert BOOKS_STUDENT < VOLUMES_ON_LEVEL * BOOKS_IN_VOLUME, \
    "книга для преподавателя в счёт ученика не входит"

assert EXAM["вопросов"] == 100 and EXAM["минут"] == 105, "структура четвёртого уровня"
assert EXAM["порог"] * 100 // EXAM["максимум"] == 60, "порог — три пятых"
assert round(EXAM["письмо_минут"] / float(EXAM["письмо_заданий"]), 1) == 1.7, \
    "меньше двух минут на письменное задание"
