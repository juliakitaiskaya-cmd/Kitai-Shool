# -*- coding: utf-8 -*-
"""Данные к статье «Подготовка к HSK: материалы, приложения и упражнения».

Числа по письменной части взяты с наших же страниц уровней. Названий
приложений, сайтов и каналов в данных нет и быть не должно: блог их
не публикует.
"""

CONF = "подтверждено"
DESC = "по описаниям"
OURS = "наш вывод"

# ----------------------------------------------------------------- набор
# часть набора, что закрывает, чего не закрывает
KIT = [
    ("Книга с программой", "порядок тем и объём уровня",
     "не проверяет, как вы говорите и пишете"),
    ("Записи для слуха", "темп и связность живой речи",
     "не учат словам: слова нужно знать заранее"),
    ("Колода карточек", "удержание выученного",
     "не даёт нового и не заменяет текст"),
    ("Пробник целиком", "формат и распределение времени",
     "только показывает пробел, но не устраняет его"),
]

# ----------------------------------------------------------------- аудирование
# проход, что делаем, что получаем
PASSES = [
    ("Первый", "слушаем целиком, без расшифровки и без пауз",
     "понимаем, сколько держится внимание и где теряется нить"),
    ("Второй", "разбираем с расшифровкой, выписываем непонятое",
     "видим, что это было: незнакомое слово или знакомое, не узнанное на слух"),
    ("Третий", "слушаем снова без расшифровки, через день",
     "проверяем, перешло ли разобранное в узнавание"),
]

# признаки записи, с которой есть смысл работать
AUDIO_SIGNS = [
    ("есть расшифровка", "без неё второй проход невозможен"),
    ("длина одна-три минуты", "длинную не разобрать за подход, короткую не на чем проверить"),
    ("темп живой речи", "медленная запись тренирует не то"),
    ("знакомая тема", "незнакомая тема превращает слушание в угадывание"),
]

# ----------------------------------------------------------------- письмо
# уровень, заданий, минут, что именно требуется, есть ли сочинение
WRITING = [
    (3, 10, 15, "собрать предложение из слов и написать знак по пиньиню", False),
    (4, 15, 25, "собрать предложение из слов и написать фразу по картинке", False),
    (5, 10, 40, "восемь предложений из слов и два мини-сочинения", True),
]

# ----------------------------------------------------------------- карточки
# что кладём в колоду, зачем
CARDS = [
    ("слово и действие с ним", "узнать на слух, узнать глазами или написать от руки — "
                               "это три разные карточки, а не одна"),
    ("слово в предложении", "одиночное слово вспоминается хуже, чем слово в опоре"),
    ("только то, что уже встречали", "колода удерживает выученное, а не учит новому"),
]

# ----------------------------------------------------------------- расчёты
LEVELS_W = [l for l, q, m, t, s in WRITING]
WITH_ESSAY = [l for l, q, m, t, s in WRITING if s]
NO_ESSAY = [l for l, q, m, t, s in WRITING if not s]
MIN_PER_TASK = {l: round(float(m) / q, 1) for l, q, m, t, s in WRITING}
LONGEST = max(WRITING, key=lambda r: r[2])[0]

# ----------------------------------------------------------------- проверки
assert len(KIT) == 4, "в наборе четыре части"
assert all(len(x) == 3 and all(x) for x in KIT), "у каждой части названы обе стороны"
assert len(set(k[0] for k in KIT)) == 4, "части не повторяются"

assert len(PASSES) == 3, "проходов три"
assert [p[0] for p in PASSES] == ["Первый", "Второй", "Третий"], "проходы идут по порядку"
assert "без расшифровки" in PASSES[0][1] and "с расшифровкой" in PASSES[1][1] \
    and "без расшифровки" in PASSES[2][1], \
    "расшифровка появляется только на втором проходе и уходит на третьем"
assert len(AUDIO_SIGNS) == 4 and all(a and b for a, b in AUDIO_SIGNS), \
    "у каждого признака названа причина"

assert LEVELS_W == [3, 4, 5], "письмо разобрано для третьего, четвёртого и пятого уровней"
assert NO_ESSAY == [3, 4] and WITH_ESSAY == [5], \
    "сочинение есть только на пятом уровне: на четвёртом его нет"
assert all("сочинени" not in t for l, q, m, t, s in WRITING if not s), \
    "в описании заданий без сочинения слово «сочинение» не встречается"
assert LONGEST == 5, "больше всего времени на письмо дают на пятом уровне"
assert MIN_PER_TASK[5] > MIN_PER_TASK[4] > MIN_PER_TASK[3], \
    "минут на одно задание становится больше от уровня к уровню"

assert len(CARDS) == 3 and all(a and b for a, b in CARDS), "у каждого правила колоды есть причина"

import re as _re
_TXT = [x for row in KIT + PASSES + AUDIO_SIGNS + CARDS for x in row if isinstance(x, str)]
_TXT += [t for l, q, m, t, s in WRITING]
_LAT = sorted({w for s in _TXT for w in _re.findall(r"[A-Za-z]{2,}", s)})
assert not _LAT, "в данных латиница: %s" % _LAT
_NAMES = [w for s in _TXT for w in _re.findall(r"Anki|Pleco|Duolingo|Quizlet|Квизлет", s)]
assert not _NAMES, "названий сервисов в данных быть не должно: %s" % _NAMES
